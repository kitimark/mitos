  cp "$work/now/dashboard.json" "$work/read/dashboard.json"
  for f in comments review-comments reviews; do cp "$work/now/$f.json" "$work/read/$f-7.json"; done
  jq -n --arg h "$H" --arg o "$other" '
    def run(id; name; app; head; n): {id: id, name: name, app: {slug: app}, head_sha: head,
