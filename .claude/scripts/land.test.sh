    jq -n --argjson id "${POST_ID:-7001}" --arg app "${POST_APP:-claude}" \
      '{id: $id, performed_via_github_app: (if $app == "none" then null else {slug: $app} end)}' ;;
  "PUT repos/acme/widgets/pulls/7/merge")
    case ${MERGE:-ok} in
