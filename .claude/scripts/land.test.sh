#!/usr/bin/env bash
# shellcheck disable=SC2016
# Usage: land.test.sh [--mutants]
#
# With --mutants it runs itself against one edited copy of land.sh or lib/land-snapshot.sh per
# `mutant` line, and fails when a copy passes every case.
set -u
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
script=${LAND_SH:-$here/land.sh}
lib=$(dirname "$script")/lib/land-snapshot.sh
failed=0

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

real=${LAND_TEST_GATE:-}
if [ -z "$real" ]; then
  (cd "$root" && lake build mitos-gate >/dev/null) || { echo "FAIL  lake build mitos-gate"; exit 1; }
  real=$root/.lake/build/bin/mitos-gate
fi
[ -x "$real" ] || { echo "FAIL  no mitos-gate at $real"; exit 1; }

check() {
  if [ "$2" = "$3" ]; then echo "ok    $1"; else
    echo "FAIL  $1"; printf '      got:  %q\n      want: %q\n' "$2" "$3"; failed=1
  fi
}

if [ "${1:-}" = --mutants ]; then
  n=0
  mutant() {
    local file=$1 name=$2 copy
    n=$((n + 1))
    copy=$work/m$n
    mkdir -p "$copy/lib"
    cp "$here/land.sh" "$copy/land.sh"
    cp "$here"/lib/*.sh "$copy/lib/"
    printf '%s\n' "$name" >"$copy/name"
    sed -i -e "$3" "$copy/$file"
    if cmp -s "$copy/$file" "$here/$file"; then
      echo unapplied >"$copy/exit"
      return
    fi
    (
      LAND_SH=$copy/land.sh LAND_TEST_GATE=$real "$0" >"$copy/log" 2>&1
      echo $? >"$copy/exit"
    ) &
    [ $((n % ${LAND_TEST_JOBS:-4})) != 0 ] || wait
  }
  in_merge='/^  merge)$/,/^  enter)$/'
  in_enter='/^  enter)$/,/^  wait)$/'
  mutant land.sh "the merge is not pinned" 's/ -f "sha=\$head"//'
  mutant land.sh "the merge is a squash" 's/merge_method=rebase/merge_method=squash/'
  mutant land.sh "the merge does not read again" "$in_merge"'s/^    read_again$/    :/'
  mutant land.sh "the record is posted without a read again" "$in_enter"'s/^    read_again$/    :/'
  mutant land.sh "a changed read is written on anyway" 's/^    1) answer "waiting: #\$pr changed since the read" 3 ;;$/    1) ;;/'
  mutant land.sh "a failed read again only waits" 's/^    \*) die "cannot read #\$pr again" ;;$/    *) answer "waiting: #$pr changed since the read" 3 ;;/'
  mutant land.sh "the read again ignores an edit time" 's/(.updated_at \/\/ .submitted_at \/\/ ""), //'
  mutant land.sh "the read again ignores a body" '/^talk_view=/s/, (.body \/\/ "")//'
  mutant land.sh "the read again ignores the state of a review" '/^talk_view=/s/ (.state \/\/ ""),//'
  mutant land.sh "the read again skips the reviews" 's/for f in comments review-comments reviews/for f in comments review-comments/'
  mutant land.sh "the read again skips the review comments" 's/for f in comments review-comments reviews/for f in comments reviews/'
  mutant land.sh "the read again ignores the head" 's/\[.state, .draft, .head.sha, /[.state, .draft, /'
  mutant land.sh "the read again ignores a draft" 's/\[.state, .draft, /[.state, /'
  mutant land.sh "the read again ignores the base" 's/ .base.ref, .base.repo.full_name,$//'
  mutant land.sh "the read again ignores the labels" 's/(\[.labels\[\].name\] | sort), //'
  mutant land.sh "the read again ignores the body of the pull request" '/(\[.labels/s/, (.body \/\/ "")\]/]/'
  mutant land.sh "the read again ignores the dashboard" 's/^  same "\$board_view" .*$/  :/'
  mutant land.sh "the read again ignores a closed dashboard" 's/\[.title, .state, /[.title, /'
  mutant land.sh "a record without the app counts" 's/^    \[ "\$slug" = "\$app" \] \\$/    false \\/'
  mutant land.sh "a record that is read and no word is posted again" 's/if \[ "\$was" = "\$about" \] &&/if false \&\&/'
  mutant land.sh "a record of another head stops a new one" 's/if \[ "\$was" = "\$about" \] &&/if true \&\&/'
  mutant land.sh "a remembered record stops though the read lacks it" 's/any(.\[\]\[\]; .id == \$id)/true/'
  mutant land.sh "the record is not remembered" 's/^    printf .%s %s\\n. "\$about" "\$id" >"\$posted".*$/    :/'
  mutant land.sh "the record names another task" 's/kind: "land", task: \$n,/kind: "land", task: ($n + 1),/'
  mutant land.sh "the record has no footer" 's/\\n\\n---\\n_Generated by \[Claude Code\](https:\/\/claude.ai\/code)_//'
  mutant land.sh "a pending gate is re-run" 's/if \[ "\$gate" = cancelled \] &&/if true \&\&/'
  mutant land.sh "a third attempt is re-run" 's/ and \. < 3)/ and . < 9)/'
  mutant land.sh "a run with no attempt number is re-run" 's/(.run_attempt | type == "number" and \. < 3)/.run_attempt < 3/'
  mutant land.sh "a run that is not over is re-run" 's/\.status == "completed" and (/(/'
  mutant land.sh "the oldest gate run is re-run" 's/max_by(.id)/min_by(.id)/'
  mutant land.sh "the gate run of another app is re-run" 's/ and \.app\.slug == "github-actions"//'
  mutant land.sh "the gate run of another head is re-run" 's/^      and \.head_sha == \$h)\]/      )]/'
  mutant land.sh "present merges" 's/^  merge)$/  merge | present)/; s/^  present)$/  present-off)/'
  mutant land.sh "awaitPush merges" 's/^  merge)$/  merge | awaitPush)/; s/^  awaitPush)$/  awaitPush-off)/'
  mutant land.sh "a 422 only waits" 's/^      405 | 409)$/      405 | 409 | 422)/'
  mutant land.sh "a merge that did not merge is called merged" 's/^        die "the merge call answered, but .*$/        :/'
  mutant land.sh "the words of GitHub are printed as they are" '/^        said=/s/ | clean)$/)/'
  mutant land.sh "a step with a short commit merges" "$in_merge"'s/^    sha "\$head" || die .*$/    :/'
  mutant land.sh "a closed pull request is decided" 's/^    closed) answer "stopped: closed" 1 ;;$/    closed) ;;/'
  mutant land.sh "a merged pull request is fetched" '/^    merged)$/,/answer "merged \$(short "\$head")" 0 ;;/c\    merged) ;;'
  mutant land.sh "the caller is another teammate" 's/teammate=orchestrator/teammate=worker/'
  mutant land.sh "the caller is another provider" 's/^provider=claude /provider=grok /'
  mutant land.sh "a second run is not refused" 's/^flock -n "\$pr_lock" || die .*$/flock -n "$pr_lock" || true/'
  mutant land.sh "two pull requests are taken" 's/^\[ \$# = 1 \] && //'
  mutant land.sh "a stop prints no read line" '/^  stop)$/,/^esac$/s/^    as_read$/    :/'
  mutant land.sh "held prints no fetch or snapshot line" 's/^        held_lines$/        :/'
  mutant land.sh "held prints the lines of every pull request" 's/grep -hEv "\$named"/grep -hE ""/'
  mutant land.sh "the read line shows a word the tool did not say" 's/\.word | strings/"stands"/'
  mutant lib/land-snapshot.sh "the fetch has no deadline" 's/^  timeout -k 5 "\$step_seconds" "\$tool_dir/  "$tool_dir/'
  mutant lib/land-snapshot.sh "the snapshot has no deadline" 's/timeout -k 5 "\$step_seconds" "\$tool_bin" snapshot/"$tool_bin" snapshot/'
  mutant lib/land-snapshot.sh "the fetch is the one in the tree of the caller" 's/"\$tool_dir\/gate\/snapshot-fetch.sh"/gate\/snapshot-fetch.sh/'
  mutant lib/land-snapshot.sh "the dashboard number is the one in the tree of the caller" 's/"\$tool_dir\/.github\/workflows\/land.yml"/.github\/workflows\/land.yml/'
  mutant lib/land-snapshot.sh "the snapshot runs in the tree of the caller" 's/(cd "\$tool_dir" && timeout/(timeout/'
  mutant lib/land-snapshot.sh "two dashboard numbers pick the first" 's/land.yml" 2>\/dev\/null)$/land.yml" 2>\/dev\/null | head -n 1)/'
  mutant lib/land-snapshot.sh "a relative folder is taken" '/takes an absolute folder/d'
  wait
  passed=0
  for i in $(seq "$n"); do
    name=$(cat "$work/m$i/name")
    fails=$(grep -c '^FAIL' "$work/m$i/log" 2>/dev/null)
    case $(cat "$work/m$i/exit" 2>/dev/null) in
      unapplied) echo "FAIL  the edit changed nothing: $name"; failed=1 ;;
      0) echo "FAIL  every case passes: $name"; passed=$((passed + 1)); failed=1 ;;
      *)
        if [ "${fails:-0}" -gt 0 ]; then echo "ok    $fails checks fail: $name"; else
          echo "FAIL  the suite did not run: $name"; failed=1
        fi ;;
    esac
  done
  echo "land mutants: $n tried, $passed passed every case"
  exit "$failed"
fi

