  jq -n --arg h "$H" --arg b "the change$footer" '{number: 7, state: "open", draft: false, merged_at: null,
    head: {sha: $h, ref: "feature", repo: {full_name: "acme/widgets"}},
    base: {ref: "main", repo: {full_name: "acme/widgets"}}, labels: [{name: "tooling"}], body: $b}' \
    >"$work/now/pr.json"
  jq -n --arg t "$t" '[[{id: 6001, user: {login: "owner"}, performed_via_github_app: null,
    created_at: $t, updated_at: $t, body: "looks fine"}]]' >"$work/now/comments.json"
  jq -n --arg t "$t" '[[{id: 6101, pull_request_review_id: 6201, user: {login: "owner"},
    created_at: $t, updated_at: $t, body: "a nit"}]]' >"$work/now/review-comments.json"
  jq -n --arg t "$t" --arg h "$H" '[[{id: 6201, user: {login: "owner"}, state: "COMMENTED",
    commit_id: $h, submitted_at: $t, body: "one"}]]' >"$work/now/reviews.json"
  jq -n '{number: 43, title: "Owner dashboard", state: "open", user: {login: "owner"}, body: "verdicts"}' \
    >"$work/now/dashboard.json"
  jq -n '{status: "completed", run_attempt: 1}' >"$work/now/run-901.json"
