#!/usr/bin/env bash
# Offline test of open-pr.sh. A fake gh plays GitHub behind the session proxy: a create rewrites the
# body the way the #91 probe saw (a plain footer's URL becomes a session link; a body without it
# gets a footer with a session link), and a PATCH stores the body as sent. FAKE_STICKY=1 makes the
# PATCH keep the link, FAKE_CLEAN=1 makes the create keep the body, and FAKE_FAIL=<POST|PATCH|GET>
# fails that method; FAKE_TITLE_LINK=1 makes the create put a session link in the title. PATH holds the fake and the system directories only.
set -u
script="$(cd "$(dirname "$0")" && pwd)/open-pr.sh"
failed=0

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
git init -q "$work/repo"
git -C "$work/repo" remote add origin "http://x-access-token:SECRET123@127.0.0.1:1234/git/acme/widgets.git"
mkdir "$work/bin"
cat >"$work/bin/gh" <<'EOF'
#!/usr/bin/env bash
echo "$*" >>"$FAKE_DIR/calls"
[ "${1:-}" = api ] || exit 1
shift
method=GET route= bodyfile= jqf= titlearg=
while [ $# -gt 0 ]; do
  case $1 in
    -X) method=$2; shift 2 ;;
    -F|-f) case $2 in body=@*) bodyfile=${2#body=@} ;; title=*) titlearg=${2#title=} ;; esac; shift 2 ;;
    --jq) jqf=$2; shift 2 ;;
    *) route=$1; shift ;;
  esac
done
[ "${FAKE_FAIL:-}" = "$method" ] && { echo "gh: HTTP 502" >&2; exit 1; }
link='https://claude.ai/code/session_01FAKEsession'
state=$FAKE_DIR/body
case "$method $route" in
  "POST repos/acme/widgets/pulls")
    b=$(cat "$bodyfile")
    if [ -z "${FAKE_CLEAN:-}" ]; then
      if grep -qF '(https://claude.ai/code)_' <<<"$b"; then b=${b//(https:\/\/claude.ai\/code)_/($link)_}
      else b="$b"$'\n\n---\n_Generated by [Claude Code]('"$link"')_'; fi
    fi
    printf '%s' "$b" >"$state"
    if [ -n "${FAKE_TITLE_LINK:-}" ]; then titlearg="$titlearg ($link)"; fi
    printf '%s' "$titlearg" >"$FAKE_DIR/title"
    jq -n --rawfile b "$state" '{number: 7, html_url: "https://github.com/acme/widgets/pull/7", body: $b}' ;;
  "PATCH repos/acme/widgets/pulls/7")
    if [ -z "${FAKE_STICKY:-}" ]; then
      cat "$bodyfile" >"$state"
      if [ -n "$titlearg" ]; then printf '%s' "$titlearg" >"$FAKE_DIR/title"; fi
    fi
    jq -n --rawfile b "$state" '{number: 7, body: $b}' ;;
  "GET repos/acme/widgets/pulls/7")
    out=$(jq -n --rawfile b "$state" --rawfile t "$FAKE_DIR/title" '{number: 7, title: $t, body: $b}')
    if [ -n "$jqf" ]; then jq -r "$jqf" <<<"$out"; else echo "$out"; fi ;;
  *) echo "unexpected $method $route" >&2; exit 1 ;;
esac
EOF
chmod +x "$work/bin/gh"
path="$work/bin:/usr/bin:/bin"

footer=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'
printf 'Adds the thing.%s' "$footer" >"$work/body.md"
printf 'No footer here.\n' >"$work/nofooter.md"
printf 'Adds it.\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01X)_\n' >"$work/linked.md"
printf 'Adds it.\n\nClaude-Session: x\n' >"$work/trailer.md"

run() { # [VAR=value ...] -- args; sets out, code
  local envs=()
  while [ "$1" != -- ]; do envs+=("$1"); shift; done
  shift
  : >"$work/calls"; rm -f "$work/body" "$work/title"
  out=$(cd "$work/repo" && env -u GH_TOKEN -u GITHUB_TOKEN PATH="$path" FAKE_DIR="$work" \
    HTTPS_PROXY=http://127.0.0.1:9 CLAUDE_PROJECT_DIR="$work/repo" "${envs[@]}" "$script" "$@" 2>&1)
  code=$?
  printf "%s\n" "$out" >>"$work/all"
}
pass() { echo "ok    $1"; }
fail() { echo "FAIL  $1"; failed=1; }
want_code() { if [ "$code" -eq "$2" ]; then pass "$1: exit $2"; else fail "$1: exit $code, wanted $2: $out"; fi; }
has() { if grep -qF -- "$2" <<<"$out"; then pass "$1"; else fail "$1: no '$2' in: $out"; fi; }
calls() { # name, wanted count of a method
  local got
  got=$(grep -c -- "$2" "$work/calls")
  if [ "$got" -eq "$3" ]; then pass "$1"; else fail "$1: $got calls matching '$2', wanted $3"; fi
}
final_clean() {
  if grep -q 'claude\.ai/code/session_' "$work/body"; then fail "$1: the stored body holds the link"
  else pass "$1: the stored body is clean"; fi
}

run -- --head feat --title "Add the thing" --body-file "$work/body.md"
want_code "a create the proxy rewrites" 0
has "it prints the PR" "open-pr: #7 https://github.com/acme/widgets/pull/7"
has "it says the create was rewritten" "came back with a session link at create"
has "it says the read-back after the PATCH is clean" "read back clean after the PATCH"
calls "one POST" '^api -X POST repos/acme/widgets/pulls ' 1
calls "one PATCH" '^api -X PATCH repos/acme/widgets/pulls/7 ' 1
calls "two read-backs" '^api repos/acme/widgets/pulls/7 --jq' 2
final_clean "a rewritten create"
if cmp -s "$work/body" "$work/body.md"; then pass "the stored body is the body file"; else fail "the stored body differs from the file"; fi

run -- --head feat --title "t" --body-file "$work/nofooter.md" --base dev --draft
want_code "a body without the footer gets a linked footer appended" 0
final_clean "an appended footer"
calls "the base and draft are sent" '-f base=dev -F body=@.* -F draft=true' 1

run FAKE_CLEAN=1 -- --head feat --title "t" --body-file "$work/body.md"
want_code "a create the proxy leaves alone" 0
has "it says the body came back clean" "came back clean at create"
calls "no PATCH when the body is clean" '-X PATCH' 0

run FAKE_STICKY=1 -- --head feat --title "t" --body-file "$work/body.md"
want_code "a PATCH that does not clean the body" 1
has "it says the link is still there" "still holds a session link after the PATCH"

run FAKE_FAIL=PATCH -- --head feat --title "t" --body-file "$work/body.md"
want_code "a failed PATCH" 1
has "it says the PATCH failed" "the PATCH of #7 failed"

run FAKE_FAIL=POST -- --head feat --title "t" --body-file "$work/body.md"
want_code "a failed create" 1
calls "no read-back after a failed create" '^api repos/acme/widgets/pulls/7' 0

run FAKE_FAIL=GET -- --head feat --title "t" --body-file "$work/body.md"
want_code "a failed read-back" 1
has "it says the read-back failed" "reading #7 back failed"

run -- --head feat --title "t" --body-file "$work/linked.md"
want_code "a body file that holds a session link" 1
calls "it is refused before any call" 'api' 0
run -- --head feat --title "t" --body-file "$work/trailer.md"
want_code "a body file with a Claude-Session line" 1
run -- --head feat --title "t"
want_code "no body file" 1
run -- --head feat --title "t" --body-file
want_code "a flag with no value at the end" 1
run -- --head 'feat;rm' --title "t" --body-file "$work/body.md"
want_code "a branch name with a shell character" 1
run -- --head feat --title "t" --body-file "$work/none.md"
want_code "a missing body file" 1

# The title: a link or a Claude-Session line in it is refused before any call, and a title the
# proxy rewrites is patched and read back.
run -- --head feat --title "Add the thing https://claude.ai/code/session_01X" --body-file "$work/body.md"
want_code "a title that holds a session link" 1
has "it names the title" "the title holds a session link"
calls "it is refused before any call" 'api' 0
run -- --head feat --title "Add it Claude-Session: x" --body-file "$work/body.md"
want_code "a title with a Claude-Session line" 1
has "it names the Claude-Session line in the title" "the title holds a Claude-Session line"
calls "that is refused before any call too" 'api' 0
run FAKE_CLEAN=1 FAKE_TITLE_LINK=1 -- --head feat --title "Add the thing" --body-file "$work/body.md"
want_code "a title the proxy rewrites with a link" 0
has "it says the create was rewritten" "came back with a session link at create"
calls "it patches the title" '^api -X PATCH repos/acme/widgets/pulls/7 -f title=Add the thing ' 1
if grep -q 'claude\.ai/code/session_' "$work/title"; then fail "the stored title holds the link"; else pass "the stored title is clean"; fi
run FAKE_CLEAN=1 FAKE_TITLE_LINK=1 FAKE_STICKY=1 -- --head feat --title "Add the thing" --body-file "$work/body.md"
want_code "a title that stays linked after the PATCH" 1
has "it says the link is still there" "still holds a session link after the PATCH"

if grep -q -e SECRET123 -e 127.0.0.1:1234 "$work/all"; then fail "the origin URL was printed"; else pass "the origin URL is never printed"; fi
exit "$failed"
