#!/usr/bin/env bash
# shellcheck disable=SC2016 # the single-quoted $names are jq variables
# Offline test of bot-review.sh. A fake gh answers from fixture files and never calls the real one:
# PATH holds the fake and the system directories only, the token is a dummy and the proxy is dead.
set -u
script="$(cd "$(dirname "$0")" && pwd)/bot-review.sh"
failed=0

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# A scratch repo whose origin carries a token, to prove the URL is parsed and never printed.
git init -q "$work/repo"
git -C "$work/repo" remote add origin "http://x-access-token:SECRET123@127.0.0.1:1234/git/acme/widgets.git"

mkdir "$work/bin" "$work/f"
cat >"$work/bin/gh" <<'EOF'
#!/usr/bin/env bash
# Fake gh: answers `gh api [flags] <route>` from $FAKE_DIR/f. A POST of a comment stores its body
# in $FAKE_DIR/posted and answers id 4242. FAKE_MODE=fail fails every call, and a route that
# contains $FAKE_FAIL fails. Every call is logged to $FAKE_DIR/calls on one line.
printf '%s\n' "$*" | tr '\n' ' ' >>"$FAKE_DIR/calls"
echo >>"$FAKE_DIR/calls"
[ "${1:-}" = api ] || exit 1
shift
route= method=GET body=
while [ $# -gt 0 ]; do
  case $1 in
    -X) method=$2; shift 2 ;;
    -f) body=${2#body=}; shift 2 ;;
    -*) shift ;;
    *) route=$1; shift ;;
  esac
done
[ "${FAKE_MODE:-}" = fail ] && { echo "gh: HTTP 502" >&2; exit 1; }
[ -n "${FAKE_FAIL:-}" ] && [[ $route == *"$FAKE_FAIL"* ]] && { echo "gh: HTTP 500" >&2; exit 1; }
f=$FAKE_DIR/f
case "$method $route" in
  "GET repos/acme/widgets/pulls/86") cat "$f/pr.json" ;;
  "GET repos/acme/widgets/commits/"*"/check-runs?check_name=CodeRabbit&filter=all&per_page=100")
    s=${route#repos/acme/widgets/commits/}; s=${s%%/*}
    if [ -e "$f/checks-$s.json" ]; then cat "$f/checks-$s.json"; else echo '{"total_count":0,"check_runs":[]}'; fi ;;
  "GET repos/acme/widgets/pulls/86/reviews?per_page=100") cat "$f/reviews.json" ;;
  "GET repos/acme/widgets/issues/86/comments?per_page=100") cat "$f/comments.json" ;;
  "POST repos/acme/widgets/issues/86/comments") printf '%s' "$body" >"$FAKE_DIR/posted"; echo '{"id":4242}' ;;
  *) echo "unexpected $method $route" >&2; exit 1 ;;
esac
EOF
chmod +x "$work/bin/gh"
path="$work/bin:/usr/bin:/bin"
[ -x "$work/bin/gh" ] && [ "$(PATH=$path type -P gh)" = "$work/bin/gh" ] || { echo "FAIL  gh is not the fake"; exit 1; }

sha() { printf "$1%.0s" $(seq 40); } # 40 copies of one hex digit
A=$(sha a) B=$(sha b) C=$(sha c)
footer=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
summary_tag='<!-- This is an auto-generated comment: summarize by coderabbit.ai -->'
paused_tag='<!-- This is an auto-generated comment: review paused by coderabbit.ai -->'

# Fixtures: PR 86 at head A. CodeRabbit reviewed B, then replied in a thread at A (an empty body).
pr() { jq -n --arg h "$1" --arg s "${2:-open}" '{number:86, state:$s, head:{sha:$h}}' >"$work/f/pr.json"; }
check() { # sha, then the runs as a jq array
  jq -n --arg h "$1" "{total_count:1, check_runs:($2 | map(. + {head_sha:\$h}))}" >"$work/f/checks-$1.json"
}
cr() { # id, status, conclusion, title: one run of the CodeRabbit app
  printf '{id:%s,name:"CodeRabbit",app:{slug:"coderabbitai"},status:"%s",conclusion:%s,completed_at:"2026-11-09T10:00:00Z",output:{title:"%s"}}' "$1" "$2" "$3" "$4"
}
summary() { # the body of CodeRabbit's summary comment
  jq -n --arg b "$1" '[[{id:10,user:{login:"coderabbitai[bot]"},author_association:"NONE",created_at:"2026-11-09T09:00:00Z",body:$b}]]' >"$work/f/comments.json"
}
add_comment() { # id, login, association, created_at, body
  jq --argjson id "$1" --arg u "$2" --arg a "$3" --arg t "$4" --arg b "$5" \
    '.[0] += [{id:$id, user:{login:$u}, author_association:$a, created_at:$t, body:$b}]' \
    "$work/f/comments.json" >"$work/f/c.new" && mv "$work/f/c.new" "$work/f/comments.json"
}
pr "$A"
jq -n --arg a "$A" --arg b "$B" '[[
  {id:1,user:{login:"coderabbitai[bot]"},state:"COMMENTED",commit_id:$b,submitted_at:"2026-11-09T08:00:00Z",body:"**Actionable comments posted: 2**"},
  {id:2,user:{login:"coderabbitai[bot]"},state:"COMMENTED",commit_id:$a,submitted_at:"2026-11-09T09:30:00Z",body:""}]]' >"$work/f/reviews.json"
summary "$summary_tag walkthrough"
check "$A" "[$(cr 5 completed '"success"' Finished)]"

envs() { # the environment of every run: no real token, a dead proxy, the fake gh first on PATH
  env -u GH_HOST -u GITHUB_TOKEN PATH="$path" FAKE_DIR="$work" CLAUDE_PROJECT_DIR="$work/repo" \
    GH_TOKEN=dummy HTTPS_PROXY=http://127.0.0.1:9 https_proxy=http://127.0.0.1:9 "$@"
}
run() { # arguments to the script; sets $out and $code, and keeps every output in $work/all
  rm -f "$work/posted"
  out=$(cd "$work/repo" && envs "$script" "$@" 2>&1)
  code=$?
  printf '%s\n' "$out" >>"$work/all"
}
is() { # name, exact expected output, expected exit code
  if [ "$out" = "$2" ] && [ "$code" = "$3" ]; then echo "ok    $1"; else
    echo "FAIL  $1"; printf '      got:  %q (exit %s)\n      want: %q (exit %s)\n' "$out" "$code" "$2" "$3"; failed=1
  fi
}
posted() { # name: a request was posted
  if [ -e "$work/posted" ]; then echo "ok    $1"; else echo "FAIL  $1"; failed=1; fi
}
not_posted() { # name: nothing was posted
  if [ -e "$work/posted" ]; then echo "FAIL  $1"; failed=1; else echo "ok    $1"; fi
}

run 86
is "a passed check at the head: reviewed, exit 0" "coderabbit #86: reviewed ${A:0:7}" 0
run 86 --request
is "--request on reviewed: no request" "coderabbit #86: reviewed ${A:0:7}" 0
not_posted "--request on reviewed posts nothing"

summary "$summary_tag $paused_tag
> ## Reviews paused
> - Last reviewed commit: $C
walkthrough"
check "$A" "[$(cr 5 completed '"skipped"' 'Review paused')]"
run 86
is "a paused check: paused, and the summary names the last reviewed commit" \
  "coderabbit #86: paused: last reviewed ${C:0:7}, head ${A:0:7}" 1

summary "$summary_tag walkthrough"
run 86
is "a paused check without the summary note: the newest review with a body is the last reviewed" \
  "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}" 1

run 86 --request
want=$(printf '@coderabbitai review\n\nThe head is %s, and CodeRabbit last reviewed %s (paused).%s' "${A:0:7}" "${B:0:7}" "$footer")
is "--request on paused: one request, and its id" \
  "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}
coderabbit #86: requested a review in comment 4242" 1
if [ -e "$work/posted" ] && [ "$(cat "$work/posted")" = "$want" ]; then
  echo "ok    the request starts with the command and ends with the footer"
else echo "FAIL  the request body"; printf '      got:  %q\n      want: %q\n' "$(cat "$work/posted" 2>/dev/null)" "$want"; failed=1; fi
if grep -q -- '-X POST repos/acme/widgets/issues/86/comments -f body=@coderabbitai review' "$work/calls"; then
  echo "ok    the request is a POST with a raw -f field, so the @ is not read as a file"
else echo "FAIL  the request call"; failed=1; fi

add_comment 20 kitimark OWNER 2026-11-09T10:05:00Z "@coderabbitai review$footer"
run 86 --request
is "--request while an earlier request is open: none posted" \
  "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}
coderabbit #86: no request posted: comment 20 already requests a review" 1
not_posted "an open request stops a second one"

add_comment 21 'coderabbitai[bot]' NONE 2026-11-09T10:06:00Z "Action not completed. Head commit changed."
run 86 --request
is "--request after CodeRabbit answered the earlier request: a new one" \
  "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}
coderabbit #86: requested a review in comment 4242" 1
posted "a request CodeRabbit answered does not stop a new one"

summary "$summary_tag walkthrough"
add_comment 22 kitimark OWNER 2026-11-09T09:55:00Z "@coderabbitai review"
add_comment 23 mallory NONE 2026-11-09T10:07:00Z "@coderabbitai review"
run 86 --request
is "--request with only a request older than the check and one from an outside account: a new one" \
  "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}
coderabbit #86: requested a review in comment 4242" 1
posted "an old request or an outside account's does not stop a new one"

summary "$summary_tag walkthrough"
check "$A" "[$(cr 5 completed '"cancelled"' 'Review cancelled')]"
run 86
is "a cancelled run at the head: behind" "coderabbit #86: behind: last reviewed ${B:0:7}, head ${A:0:7}" 1
run 86 --request
is "--request on behind: one request" "coderabbit #86: behind: last reviewed ${B:0:7}, head ${A:0:7}
coderabbit #86: requested a review in comment 4242" 1
posted "--request on behind posts"
pr "$A" closed
run 86 --request
is "--request on a closed PR: none posted" "coderabbit #86: behind: last reviewed ${B:0:7}, head ${A:0:7}
coderabbit #86: no request posted: the PR is closed" 1
not_posted "a closed PR gets no request"
pr "$A"

cp "$work/f/reviews.json" "$work/reviews.keep"
echo '[[]]' >"$work/f/reviews.json"
run 86
is "never reviewed: last reviewed none" "coderabbit #86: behind: last reviewed none, head ${A:0:7}" 1
cp "$work/reviews.keep" "$work/f/reviews.json"

check "$A" "[$(cr 5 in_progress null 'Review in progress')]"
run 86 --request
is "a run in progress: pending, and no request" "coderabbit #86: pending: last reviewed ${B:0:7}, head ${A:0:7}" 1
not_posted "--request on pending posts nothing"
rm "$work/f/checks-$A.json"
run 86
is "no check at the head and no note: pending" "coderabbit #86: pending: last reviewed ${B:0:7}, head ${A:0:7}" 1

summary "$summary_tag $paused_tag
> ## Reviews paused
> - Last reviewed commit: $B"
run 86
is "no check at the head, the summary says paused: paused" "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}" 1

summary "$summary_tag
> [!IMPORTANT]
> ## Review skipped
>
> Too many files!
>
> This PR contains 375 files, which is 75 over the limit of 300."
run 86 --request
is "no check at the head, the summary says review skipped: refused, and no request" \
  "coderabbit #86: refused: Too many files!" 1
not_posted "--request on refused posts nothing"

check "$A" "[$(cr 5 completed '"skipped"' 'Review skipped: 375 files exceed the limit of 300')]"
summary "$summary_tag walkthrough"
run 86
is "a check skipped for a reason other than a pause: refused, with its reason" \
  "coderabbit #86: refused: 375 files exceed the limit of 300" 1

jq -n --arg h "$A" --arg t $'Review skipped: x\xe2\x80\xae\x1b[31my\nz '"$(printf 'w%.0s' $(seq 200))" \
  '{check_runs:[{id:5,name:"CodeRabbit",app:{slug:"coderabbitai"},head_sha:$h,status:"completed",conclusion:"skipped",output:{title:$t}}]}' \
  >"$work/f/checks-$A.json"
run 86
reason="x 31my z $(printf 'w%.0s' $(seq 200))"
is "a refusal reason is cut to plain characters and 80 of them" "coderabbit #86: refused: ${reason:0:80}" 1

check "$A" "[$(cr 5 completed '"skipped"' 'Review paused')]"
run 86
is "back to a paused check: paused" "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}" 1

# Only CodeRabbit's own app and account count: another app's check named CodeRabbit, a review or a
# summary from another account change nothing.
check "$A" "[$(cr 5 completed '"skipped"' 'Review paused'),
  {id:6,name:\"CodeRabbit\",app:{slug:\"github-actions\"},status:\"completed\",conclusion:\"success\",output:{title:\"Finished\"}}]"
jq --arg a "$A" '.[0] += [{id:3,user:{login:"mallory"},state:"COMMENTED",commit_id:$a,submitted_at:"2026-11-09T11:00:00Z",body:"LGTM"}]' \
  "$work/f/reviews.json" >"$work/f/r.new" && mv "$work/f/r.new" "$work/f/reviews.json"
add_comment 30 mallory NONE 2026-11-09T11:00:00Z "$summary_tag $paused_tag Last reviewed commit: $A"
run 86
is "another app's check, another account's review or summary: still paused" \
  "coderabbit #86: paused: last reviewed ${B:0:7}, head ${A:0:7}" 1

# A review from CodeRabbit with a body at the head counts as reviewed, even with no check.
jq --arg a "$A" '.[0] += [{id:4,user:{login:"coderabbitai[bot]"},state:"COMMENTED",commit_id:$a,submitted_at:"2026-11-09T12:00:00Z",body:"**Actionable comments posted: 1**"}]' \
  "$work/f/reviews.json" >"$work/f/r.new" && mv "$work/f/r.new" "$work/f/reviews.json"
rm "$work/f/checks-$A.json"
run 86
is "CodeRabbit's review of the head with no check: reviewed" "coderabbit #86: reviewed ${A:0:7}" 0

# Errors: usage, a failed call, a head that is not a commit.
run
is "no PR: usage" "bot-review: usage: bot-review.sh <pr> [--request]" 2
run abc
is "a PR that is not a number: usage" "bot-review: usage: bot-review.sh <pr> [--request]" 2
run 86 87
is "two PRs: usage" "bot-review: usage: bot-review.sh <pr> [--request]" 2
run 86 --force
is "an unknown flag: usage" "bot-review: usage: bot-review.sh <pr> [--request]" 2
out=$(cd "$work/repo" && envs FAKE_MODE=fail "$script" 86 2>&1); code=$?
is "GitHub fails: one line, exit 2" "bot-review: cannot read PR #86" 2
out=$(cd "$work/repo" && envs FAKE_FAIL=reviews "$script" 86 2>&1); code=$?
is "one call fails: one line, exit 2" "bot-review: cannot read the reviews of PR #86" 2
echo '{"number":86,"state":"open","head":{"sha":"$(touch PWNED)"}}' >"$work/f/pr.json"
run 86
is "a head that is not a commit SHA: refused" "bot-review: PR #86 has no head commit" 2
pr "$A"
echo '{"check_runs":"oops"}' >"$work/f/checks-$A.json"
run 86
is "a check list of the wrong shape: refused" "bot-review: unexpected JSON from GitHub for PR #86" 2

if grep -q -e SECRET123 -e 127.0.0.1:1234 "$work/all"; then
  echo "FAIL  the origin URL was printed"; failed=1
else echo "ok    the origin URL is never printed"; fi
if grep -v '^api ' "$work/calls" | grep -q . \
  || grep -v -- '-X POST repos/acme/widgets/issues/86/comments -f body=@coderabbitai review' "$work/calls" \
    | grep -q -e ' -X' -e ' --method' -e ' -f ' -e ' -F '; then
  echo "FAIL  a call was not a gh api read or the one request"; failed=1
else echo "ok    every call is a gh api read, or the request's POST ($(wc -l <"$work/calls") calls)"; fi

exit "$failed"
