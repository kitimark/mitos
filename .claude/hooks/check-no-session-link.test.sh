#!/usr/bin/env bash
# shellcheck disable=SC2016 # backticks and $4 in single quotes are meant literally
# Tests for check-no-session-link.sh. Run: .claude/hooks/check-no-session-link.test.sh
# Each case feeds one PreToolUse input and wants exit 2 (blocked, with a message on stderr) or exit
# 0 (allowed, silent).
set -u
hook="$(cd "$(dirname "$0")" && pwd)/check-no-session-link.sh"
failed=0

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
mkdir "$work/scratch"
link='https://claude.ai/code/session_01ABCdefGHI'
footer=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n'
printf 'Fixes the thing.%s' "$footer" >"$work/clean.md"
printf 'Fixes the thing.\n\n---\n_Generated by [Claude Code](%s)_\n' "$link" >"$work/link.md"
printf 'Fix the thing\n\nCo-Authored-By: A <a@example.com>\nClaude-Session: %s\n' "$link" >"$work/trailer.txt"
printf 'Fix the thing\n\nClaude-Session: x\n' >"$work/scratch/msg.txt"
printf 'Fix the thing\n\nCo-Authored-By: A <a@example.com>\n' >"$work/scratch/okmsg.txt"
printf 'Fix the thing.%s' "$footer" >"$work/scratch/body.md"
printf 'Fix the thing.\n\n%s\n' "$link" >"$work/scratch/bad.md"
printf 'We dropped the `Claude-Session:` trailer.%s' "$footer" >"$work/mention.md"
jq -n --arg b "x $link" '{title:"t", body:$b}' >"$work/input.json"

bash_in() { # command -> hook input
  jq -cn --arg c "$1" --arg cwd "$work" '{tool_name:"Bash", cwd:$cwd, tool_input:{command:$c}}'
}
mcp_in() { # tool name, input JSON
  jq -cn --arg t "$1" --argjson i "$2" --arg cwd "$work" '{tool_name:$t, cwd:$cwd, tool_input:$i}'
}
check() { # name, input, want (block|allow), [stderr substring]
  local err code
  err=$("$hook" <<<"$2" 2>&1 >/dev/null)
  code=$?
  if [ "$3" = block ]; then
    if [ "$code" -eq 2 ] && [ -n "$err" ] && { [ -z "${4:-}" ] || grep -qF -- "$4" <<<"$err"; }; then
      echo "ok    $1: blocked"
    else echo "FAIL  $1: wanted a block${4:+ with '$4'}, got exit $code: $err"; failed=1; fi
  else
    if [ "$code" -eq 0 ] && [ -z "$err" ]; then echo "ok    $1: allowed"
    else echo "FAIL  $1: wanted allowed, got exit $code: $err"; failed=1; fi
  fi
}

# The session link.
check "gh api comment with the link inline" \
  "$(bash_in "gh api repos/o/r/issues/5/comments -f body='done $link'")" block "session link"
check "gh api PATCH with a body file that holds the link" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F body=@$work/link.md")" block "link.md"
check "the block message gives the sed fix" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F body=@$work/link.md")" block "sed -i -E 's#https://claude\\.ai/code/session_"
check "a relative body file is read from cwd" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F body=@link.md")" block "link.md"
check "a relative body file after a leading cd" \
  "$(bash_in "cd scratch && gh api repos/o/r/issues/5/comments -F body=@bad.md")" block "bad.md"
check "a body file in quotes" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F 'body=@$work/link.md'")" block "link.md"
check "gh api --input with the link in the JSON" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 --input $work/input.json")" block "input.json"
check "gh issue comment --body-file with the link" \
  "$(bash_in "gh issue comment 5 --body-file $work/link.md")" block "link.md"
check "gh issue comment -F with the link" \
  "$(bash_in "gh issue comment 5 -F $work/link.md")" block "link.md"
check "gh pr edit -F, relative, after cd" \
  "$(bash_in "cd scratch && gh pr edit 5 -F bad.md")" block "bad.md"
check "gh issue comment -F with a clean file" \
  "$(bash_in "gh issue comment 5 -F $work/clean.md")" allow
check "gh api -F fields are not files" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F draft=true -F body=@$work/clean.md")" allow
check "gh api with a clean body file" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F body=@$work/clean.md")" allow
check "clean body after cd" \
  "$(bash_in "cd scratch && gh api repos/o/r/issues/5/comments -F body=@body.md")" allow
check "the sed fix itself with gh in the same command" \
  "$(bash_in "sed -i -E 's#https://claude\\.ai/code/session_[A-Za-z0-9_-]+#https://claude.ai/code#g' $work/clean.md && gh api -X PATCH repos/o/r/pulls/5 -F body=@$work/clean.md")" allow
check "a body file named by a variable is skipped" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F body=@\$f")" allow
check "a missing body file is skipped" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/5 -F body=@$work/none.md")" allow
check "the link in a command that is not gh or git commit" \
  "$(bash_in "echo $link")" allow
check "a read of the link through gh api with --jq" \
  "$(bash_in "gh api repos/o/r/pulls/5 --jq '.body | test(\"session_\")'")" allow

# The Claude-Session line.
check "git commit -m with the trailer" \
  "$(bash_in "git commit -m 'Fix' -m 'Claude-Session: abc'")" block "Claude-Session"
check "git commit with the trailer in a heredoc" \
  "$(bash_in $'git commit -F - <<EOF\nFix\n\nClaude-Session: x\nEOF')" block "Claude-Session"
check "git -C dir commit with the trailer" \
  "$(bash_in "git -C /x commit -m \"\$(printf 'Fix\n\nClaude-Session: y')\"")" block "Claude-Session"
check "git commit -F with a message file that holds the trailer" \
  "$(bash_in "git commit -F $work/trailer.txt")" block "trailer.txt"
check "git commit --file= after cd" \
  "$(bash_in "cd scratch && git commit --file=msg.txt")" block "msg.txt"
check "git commit with a clean message file" \
  "$(bash_in "cd scratch && git commit -F okmsg.txt")" allow
check "git commit -m without the trailer" \
  "$(bash_in "git commit -m 'Fix the thing' -m 'Co-Authored-By: A <a@example.com>'")" allow
check "git commit-tree is not git commit" \
  "$(bash_in "git commit-tree abc -m 'Claude-Session: x'")" allow
check "a body that mentions the trailer mid-line" \
  "$(bash_in "gh api repos/o/r/issues/5/comments -F body=@$work/mention.md")" allow
check "a gh body with the trailer as its own line" \
  "$(bash_in "gh api repos/o/r/issues/5/comments -f body=\$'done\nClaude-Session: x'")" block "Claude-Session"
check "git log grep for the trailer" \
  "$(bash_in "git log --grep 'Claude-Session:'")" allow

# A PR create that skips open-pr.sh.
check "gh api -X POST to the pulls route" \
  "$(bash_in "gh api -X POST repos/kitimark/mitos/pulls -f title=t -f head=h -f base=main -F body=@$work/clean.md")" block "open-pr.sh"
check "gh api --method=POST with placeholders" \
  "$(bash_in "gh api --method=POST 'repos/{owner}/{repo}/pulls' -f title=t")" block "open-pr.sh"
check "gh api with fields and no method (POST by default)" \
  "$(bash_in "gh api repos/o/r/pulls -f title=t -f head=h -f base=main")" block "open-pr.sh"
check "gh api --input and no method" \
  "$(bash_in "jq -n '{title:1}' | gh api repos/o/r/pulls --input -")" block "open-pr.sh"
check "a create whose fields follow a line continuation" \
  "$(bash_in $'gh api repos/o/r/pulls \\\n  -f title=t -f head=h -f base=main')" block "open-pr.sh"
check "a create whose -X POST follows a line continuation" \
  "$(bash_in $'gh api \\\n  -X POST \\\n  repos/o/r/pulls --input body.json')" block "open-pr.sh"
check "a create on repos/\$repo/pulls" \
  "$(bash_in "gh api repos/\$repo/pulls -f title=t -f head=h -f base=main")" block "open-pr.sh"
check "a PATCH on repos/\$repo/pulls/\$n" \
  "$(bash_in "gh api -X PATCH repos/\$repo/pulls/\$n -F body=@$work/clean.md")" allow
check "a continued read of the pulls list" \
  "$(bash_in $'gh api \\\n  \'repos/o/r/pulls?state=open\' --jq \'.[].number\'')" allow
check "gh pr create" \
  "$(bash_in "gh pr create --title t --body-file $work/clean.md")" block "open-pr.sh"
check "the pulls list is a read" \
  "$(bash_in "gh api 'repos/o/r/pulls?state=open&per_page=100' --jq '.[] | .number'")" allow
check "the pulls list with -X GET and a field" \
  "$(bash_in "gh api -X GET repos/o/r/pulls -f state=open")" allow
check "a PATCH of one PR" \
  "$(bash_in "gh api -X PATCH repos/o/r/pulls/91 -f state=closed")" allow
check "a reply on a review comment" \
  "$(bash_in "gh api repos/o/r/pulls/91/comments/77/replies -F body=@$work/clean.md")" allow
check "a merge pinned to a head" \
  "$(bash_in "gh api -X PUT repos/o/r/pulls/91/merge -f merge_method=rebase -f sha=abc")" allow
check "open-pr.sh" \
  "$(bash_in ".claude/scripts/open-pr.sh --head h --title t --body-file $work/clean.md")" allow

# The GitHub MCP tools.
check "MCP create_pull_request" \
  "$(mcp_in mcp__github__create_pull_request '{"owner":"o","repo":"r","title":"t","head":"h","base":"main","body":"x"}')" block "open-pr.sh"
check "MCP add_issue_comment with the link" \
  "$(mcp_in mcp__github__add_issue_comment "$(jq -cn --arg b "x $link" '{owner:"o",repo:"r",issue_number:5,body:$b}')")" block "session link"
check "MCP update_pull_request with the link" \
  "$(mcp_in mcp__github__update_pull_request "$(jq -cn --arg b "x $link" '{owner:"o",repo:"r",pullNumber:5,body:$b}')")" block "session link"
check "MCP push_files with the trailer in the message" \
  "$(mcp_in mcp__github__push_files '{"owner":"o","repo":"r","branch":"b","files":[],"message":"Fix\n\nClaude-Session: x"}')" block "Claude-Session"
check "MCP add_reply_to_pull_request_comment, clean" \
  "$(mcp_in mcp__github__add_reply_to_pull_request_comment '{"owner":"o","repo":"r","pullNumber":5,"commentId":7,"body":"Fixed in abc."}')" allow
check "MCP search_issues for the link is a read" \
  "$(mcp_in mcp__github__search_issues "$(jq -cn --arg q "$link" '{query:$q}')")" allow
check "MCP pull_request_read is a read" \
  "$(mcp_in mcp__github__pull_request_read "$(jq -cn --arg q "$link" '{method:"get",body:$q}')")" allow

# settings.json runs the hook before Bash and every GitHub MCP tool, and not before other tools.
settings="$(dirname "$hook")/../settings.json"
matchers=$(jq -r '.hooks.PreToolUse[] | select(any(.hooks[]; .command | endswith("/check-no-session-link.sh"))) | .matcher' "$settings")
for t in Bash mcp__github__create_pull_request mcp__github__add_issue_comment; do
  if grep -qE "^($matchers)\$" <<<"$t"; then echo "ok    settings.json runs it before $t"
  else echo "FAIL  settings.json does not run it before $t (matchers: $matchers)"; failed=1; fi
done
for t in Read Agent Edit; do
  if grep -qE "^($matchers)\$" <<<"$t"; then echo "FAIL  settings.json runs it before $t"; failed=1
  else echo "ok    settings.json does not run it before $t"; fi
done

# Other tools and bad input.
check "another tool" '{"tool_name":"Read","tool_input":{"file_path":"/x"}}' allow
check "input that is not JSON" 'not json' allow
check "empty input" '' allow

exit "$failed"
