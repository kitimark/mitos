#!/usr/bin/env bash
set -u

command -v jq >/dev/null 2>&1 || exit 0
input=$(cat)
tool=$(jq -r '.tool_name // empty' <<<"$input" 2>/dev/null) || exit 0
[ -n "$tool" ] || exit 0

link_re='claude\.ai/code/session_'
trailer_re='(^|\\n|["'\''])[[:space:]>]*Claude-Session:'
open_pr_msg="Blocked: this command names a PR create: pr create or pr new, createPullRequest, or the pulls list route (/pulls) with POST, a field flag (-f, -F, --field, --input, ...) or a method other than GET. The session proxy adds a session link to the body of every PR create, so open a PR only with .claude/scripts/open-pr.sh --head <branch> --title <title> --body-file <file>, run as a command of its own; the script reads the body back and cleans it. The hook reads the text, not the shell, so a command that only mentions these words is blocked too: put the text in a file that you write with the Write tool, not with a heredoc (a heredoc holds the same words and is blocked again), then use git commit -F <file>, --body-file <file> or grep -f <file>; or use the Grep tool, or reword it. A read of the pulls list takes its filters in the query string ('repos/<owner>/<repo>/pulls?state=open'), with no -f or -X. The hook reads the whole command, so another tool's flag in the same command as a pulls read (cut -d, grep -F, jq -f, a second gh call with -X or -f) blocks it too: split the command into two calls."

block() { printf '%s\n' "$1" >&2; exit 2; }
link_msg() {
  block "Blocked: $1 holds a session link or its pattern (claude.ai/code/session_), and this repository is public. Remove it and retry, for example with sed -i -E 's#https://claude\\.ai/code/session_[A-Za-z0-9_-]+#https://claude.ai/code#g' <file>. The footer is a --- line, then _Generated by [Claude Code](https://claude.ai/code)_ (CLAUDE.md, Attribution). To search for the pattern, escape its dots: claude\\.ai/code/session_."
}
trailer_msg() {
  block "Blocked: $1 holds a Claude-Session line, which the owner dropped from commits and posts (CLAUDE.md, Attribution). Remove the line and retry, for example with sed -i '/^Claude-Session/d' <file>, or leave it out of the -m message."
}

case $tool in
  mcp__*github*__*)
    name=${tool##*__}
    case $name in get_* | list_* | search_* | *_read) exit 0 ;; esac
    [ "$name" = create_pull_request ] && block "$open_pr_msg"
    text=$(jq -c '.tool_input // {}' <<<"$input" 2>/dev/null) || exit 0
    grep -Eq "$link_re" <<<"$text" && link_msg "this $name call"
    grep -Eq "$trailer_re" <<<"$text" && trailer_msg "this $name call"
    exit 0 ;;
  Bash) ;;
  *) exit 0 ;;
esac

cmd=$(jq -r '.tool_input.command // empty' <<<"$input" 2>/dev/null) || exit 0
cwd=$(jq -r '.cwd // empty' <<<"$input" 2>/dev/null) || exit 0
gh_re='(^|[^[:alnum:]_.-])gh[[:space:]]+(api|pr|issue)([[:space:]]|$)'
commit_re='(^|[^[:alnum:]_.-])git([[:space:]]+-[Cc][[:space:]]+[^[:space:]]+)*[[:space:]]+commit([[:space:]]|$)'
is_gh=0 is_commit=0
grep -Eq "$gh_re" <<<"$cmd" && is_gh=1
grep -Eq "$commit_re" <<<"$cmd" && is_commit=1

if [ "$is_gh" = 1 ] || [ "$is_commit" = 1 ]; then
  grep -Eq "$link_re" <<<"$cmd" && link_msg "this command"
  if [ "$is_commit" = 1 ]; then
    grep -q 'Claude-Session:' <<<"$cmd" && trailer_msg "this commit message"
  fi
  grep -Eq "$trailer_re" <<<"$cmd" && trailer_msg "this command"
fi

open_pr_script_re='^[[:space:]]*([^[:space:];&|<>()`$'\''"\\]*/)?\.claude/scripts/open-pr\.sh([[:space:]]|$)'
pr_create_re='(^|[^[:alnum:]_])pr[[:space:]'\''"\\,$]+(-[^[:space:]]*[[:space:]]+([^-[:space:]][^[:space:]]*[[:space:]]+)?)*(create|new)([^[:alnum:]_]|$)|createpullrequest'
pulls_list_route_re='/pulls(/?($|[?#`[:space:];&|)<>\\])|['\''"]+($|[^[:alnum:]_'\''"])|/['\''"]+($|[^[:alnum:]_$`'\''"]))'
post_method_re='(^|[^[:alnum:]_])post([^[:alnum:]_]|$)'
field_flag_re='(^|[[:space:]'\''"])(-[A-Za-z]*[fFd]|(--field|--raw-field|--input|--data[a-z-]*|--json|--form)([[:space:]='\''"]|$))'
method_flag_re='(^|[[:space:]'\''"])(-X|--method|--request)[[:space:]=]*[^[:space:]]*'
read_method_re='get|head'

is_open_pr_alone() {
  grep -Eq "$open_pr_script_re" <<<"$1" && [[ $1 != *[$'\n'\;\&\|\<\>\`]* && $1 != *\$\(* ]]
}

if ! is_open_pr_alone "$cmd"; then
  flat=${cmd//$'\n'/ }
  grep -Eiq -- "$pr_create_re" <<<"$flat" && block "$open_pr_msg"
  if grep -Eiq -- "$pulls_list_route_re" <<<"$flat"; then
    grep -Eiq -- "$post_method_re" <<<"$flat" && block "$open_pr_msg"
    grep -Eq -- "$field_flag_re" <<<"$flat" && block "$open_pr_msg"
    grep -oE -- "$method_flag_re" <<<"$flat" \
      | sed -E 's/^[[:space:]'\''"]*(-X|--method|--request)[[:space:]=]*//; s/['\''"]//g' \
      | grep -Eviqx "$read_method_re" && block "$open_pr_msg"
  fi
fi

[ "$is_gh" = 1 ] || [ "$is_commit" = 1 ] || exit 0

cmd_dir=$cwd
if [[ $cmd =~ ^[[:space:]]*cd[[:space:]]+([^[:space:]\;\&\|]+)[[:space:]]*\&\& ]]; then
  d=${BASH_REMATCH[1]}
  d=${d#[\"\']}; d=${d%[\"\']}
  case $d in /*) cmd_dir=$d ;; *) cmd_dir=$cwd/$d ;; esac
fi

# Where `git -C <dir> commit` reads its message file: each -C joined to the one before, from cmd_dir.
git_c_commit_dirs() {
  local g flag dir d
  while IFS= read -r g; do
    [ -n "$g" ] || continue
    d=$cmd_dir
    while read -r flag dir; do
      [ "$flag" = -C ] || continue
      dir=${dir#[\"\']}; dir=${dir%[\"\']}
      case $dir in /*) d=$dir ;; *) d=$d/$dir ;; esac
    done < <(grep -oE -- '-[Cc][[:space:]]+[^[:space:]]+' <<<"$g")
    printf '%s\n' "$d"
  done < <(grep -oE -- '(^|[^[:alnum:]_.-])git([[:space:]]+-[Cc][[:space:]]+[^[:space:]]+)+[[:space:]]+commit([[:space:]]|$)' <<<"$cmd")
}
file_dirs=("$cmd_dir")
while IFS= read -r d; do file_dirs+=("$d"); done < <(git_c_commit_dirs)
files=$(
  {
    grep -oE -- '(-F|--field)[[:space:]=]+['\''"]?[A-Za-z_][A-Za-z0-9_]*(\[\])?=@[^[:space:]'\''"]+' <<<"$cmd" | sed -E 's/.*=@//'
    grep -oE -- '--(body-file|input)[[:space:]=]+['\''"]?[^[:space:]'\''"]+' <<<"$cmd" | sed -E 's/^--(body-file|input)[[:space:]=]+['\''"]?//'
    # `-F <file>` is the body file of gh pr and gh issue and the message file of git commit. A
    # path with `=` in it is left out, so gh api's `-F name=value` fields never match.
    grep -oE -- '(^|[[:space:]])(-F|--file)[[:space:]=]+['\''"]?[^[:space:]'\''"=]+([[:space:]'\''"]|$)' <<<"$cmd" \
      | sed -E 's/^[[:space:]]*(-F|--file)[[:space:]=]+['\''"]?//; s/['\''"[:space:]]+$//'
  } 2>/dev/null
)
while IFS= read -r f; do
  [ -n "$f" ] && [ "$f" != - ] || continue
  case $f in *'$'* | *'`'*) continue ;; esac
  # shellcheck disable=SC2088
  case $f in
    /*) cands=("$f") ;;
    '~/'*) cands=("$HOME/${f#'~/'}") ;;
    *) cands=(); for b in "${file_dirs[@]}"; do cands+=("$b/$f"); done ;;
  esac
  for p in "${cands[@]}"; do
    [ -f "$p" ] && [ -r "$p" ] || continue
    grep -Eq "$link_re" "$p" && link_msg "$f"
    grep -Eq '^[[:space:]>]*Claude-Session:' "$p" && trailer_msg "$f"
  done
done <<<"$files"
exit 0
