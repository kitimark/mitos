#!/usr/bin/env bash
set -u

root=$(cd "$(dirname "$0")/.." && pwd)
(cd "$root" && lake build mitos-gate >/dev/null) || { echo "FAIL lake build mitos-gate"; exit 1; }
bin="$root/.lake/build/bin/mitos-gate"
fx="$root/gate/shadow-fixtures"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

pass=0
fail=0
ok() { echo "ok   $1"; pass=$((pass + 1)); }
bad() {
  echo "FAIL $1"
  shift
  for l in "$@"; do echo "  | $l"; done
  fail=$((fail + 1))
}

got=0
"$bin" shadow "$fx/window" >"$tmp/out" 2>"$tmp/err" || got=$?
if [ "$got" = 0 ] && [ ! -s "$tmp/err" ] && diff "$fx/window.expected" "$tmp/out" >"$tmp/diff"; then
  ok "the window scores to its expected report"
else
  bad "the window scores to its expected report" "exit $got: $(cat "$tmp/err")" "$(cat "$tmp/diff")"
fi

idle="$fx/record-idle.json"
main=$(jq -r .main "$idle")
head257=$(jq -r '.outcome.snapshot.prs[] | select(.pr == 257) | .head' "$idle")
window() {
  local dir=$1 n=9001 r
  shift
  rm -rf "$dir"
  mkdir -p "$dir/records"
  for r in "$@"; do cp "$r" "$dir/records/$n-1.json"; n=$((n + 1)); done
  if [ -n "${MERGES-}" ]; then
    printf '%s\n' "$MERGES" >"$dir/merges.json"
  else
    jq -n --arg m "${BEFORE-$main}" --arg h "$head257" \
      '[{pr: 257, time: "2026-11-14T13:37:18Z", before: $m, head: $h, tree: ""}]' >"$dir/merges.json"
  fi
  printf '%s\n' "${RUNS-[]}" >"$dir/runs.json"
  jq 'map({reviews: [], reviewComments: []} + .)' "$dir/merges.json" >"$dir/m"
  mv "$dir/m" "$dir/merges.json"
  echo '{"full_name":"owner/mitos","owner":{"login":"owner"}}' >"$dir/repo.json"
  echo '[]' >"$dir/baseline.json"
}
scores() {
  local name=$1 pat=$2 got=0
  shift 2
  window "$tmp/w" "$@"
  "$bin" shadow "$tmp/w" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" = 0 ] && grep -qxE -- "$pat" "$tmp/out"; then
    ok "$name"
  else
    bad "$name" "exit $got: $(cat "$tmp/err")" "want a line: $pat" "$(cat "$tmp/out")"
  fi
}
edited() { jq -c "$2" "$idle" >"$tmp/$1.json"; echo "$tmp/$1.json"; }

window "$tmp/w" "$idle"
jq --arg h "$head257" '.[0].reviews=[{id:1,user:{login:"owner"},state:"COMMENTED",
  commit_id:$h,submitted_at:"2026-11-14T13:30:00Z",body:""}]' "$tmp/w/merges.json" >"$tmp/m"
mv "$tmp/m" "$tmp/w/merges.json"
if "$bin" shadow "$tmp/w" >"$tmp/out" 2>"$tmp/err" &&
  grep -q '#257 .*disagrees. stop noEntry' "$tmp/out" && ! grep -q 'one word away' "$tmp/out"; then
  ok "an emptied owner summary cannot assume approval"
else bad "an emptied owner summary cannot assume approval" "$(cat "$tmp/out" "$tmp/err")"; fi
jq '.[0].reviewComments=[{pull_request_review_id:1,user:{login:"owner"},
  created_at:"2026-11-14T13:30:00Z",updated_at:"2026-11-14T13:30:00Z",
  body:"Reply.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"}]' "$tmp/w/merges.json" >"$tmp/m"
mv "$tmp/m" "$tmp/w/merges.json"
if "$bin" shadow "$tmp/w" >"$tmp/out" 2>"$tmp/err" && grep -q 'one word away' "$tmp/out"; then
  ok "an empty footer thread reply leaves the assumed approval"
else bad "an empty footer thread reply leaves the assumed approval" "$(cat "$tmp/out" "$tmp/err")"; fi

scores "a real record is scored, and this build repeats its decision" \
  '#257 at d7616ac: waits\. one word away, then awaitGate; record of run 9001, 5 s old; 2 updater pushes' \
  "$idle"
scores "a real record drifts nothing" \
  'shadow: 1 merges, 1 records, 0 refused, 0 skipped, 0 drifted, 0 unreadable' "$idle"
scores "a record read in the merge's second is not paired" '#257 at d7616ac: blind\. unseen' \
  "$(edited same-second '.read = "2026-11-14T13:37:18Z"')"
scores "a record whose main moved while it read pairs with no merge" \
  '#257 at d7616ac: blind\. unseen' "$(edited moved '.mainAfter = ("f" * 40)')"
scores "a record whose main was not read pairs with no merge" \
  '#257 at d7616ac: blind\. unseen' "$(edited unread-main '.main = "" | .mainAfter = ""')"
BEFORE='' scores "a merge whose main before it was not read pairs with no record, even one that read no main" \
  '#257 at d7616ac: blind\. unseen' "$(edited moved2 '.mainAfter = ("f" * 40)')"
scores "the control: the same record with main unmoved is paired" \
  '#257 at d7616ac: waits\. .*' "$(edited unmoved '.mainAfter = .main')"
scores "of two records, the newer one before the merge is used" \
  '#257 at d7616ac: waits\. one word away, then awaitGate; record of run 9002, 3 s old; 2 updater pushes' \
  "$idle" "$(edited newer '.read = "2026-11-14T13:37:15Z"')"
scores "a record whose decision this build does not repeat is listed" \
  'record 9001-1: drifted: it printed \{"next":257,"plan":\{"kind":"idle"\}\}, and this build decides \{"next":null,"plan":\{"kind":"idle"\}\}' \
  "$(edited drift '.outcome.decision.next = 257')"
scores "a drifted record is not scored" '#257 at d7616ac: blind\. unseen' "$(edited drift2 '.outcome.decision.next = 257')"
scores "a snapshot this build refuses is drift" \
  'record 9001-1: drifted: its snapshot is refused: prs\[0\]\."extra": not a field here' \
  "$(edited refused-snapshot '.outcome.snapshot.prs[0].extra = 1')"
scores "a key the scorer does not read is ignored" \
  '#257 at d7616ac: waits\. .*' "$(edited extra-key '. + {unknown: {kind: 1}}')"
scores "an empty mainAfterSaid is read" \
  '#257 at d7616ac: waits\. .*' "$(edited said-empty '. + {mainAfterSaid: []}')"
scores "a mainAfterSaid with lines is read" \
  '#257 at d7616ac: waits\. .*' "$(edited said-lines '. + {mainAfterSaid: ["gh: HTTP 502"]}')"
m5=$(jq -r .main "$fx/record-main-after-unread.json")
BEFORE=$m5 scores "the record whose second read of main failed is decided" \
  'shadow: 1 merges, 1 records, 0 refused, 0 skipped, 0 drifted, 0 unreadable' \
  "$fx/record-main-after-unread.json"
BEFORE=$m5 scores "the record whose second read of main failed pairs with no merge of its main" \
  '#257 at d7616ac: blind\. unseen' "$fx/record-main-after-unread.json"
BEFORE=$m5 scores "the control: with its second read, that record is paired" \
  '#257 at d7616ac: blind\. not listed in run 9001' \
  "$(jq -c '.mainAfter = .main | .mainAfterSaid = []' "$fx/record-main-after-unread.json" >"$tmp/said-control.json"; echo "$tmp/said-control.json")"
scores "the refused record is counted" \
  'shadow: 1 merges, 1 records, 1 refused, 0 skipped, 0 drifted, 0 unreadable' "$fx/record-refused.json"
scores "the skipped record is counted" \
  'shadow: 1 merges, 1 records, 0 refused, 1 skipped, 0 drifted, 0 unreadable' "$fx/record-skipped.json"
scores "a record of another version is refused" \
  'record 9001-1: unreadable: v is 2, and this scorer reads v 1' "$fx/record-v2.json"
scores "the record whose main moved is decided, and pairs with no merge of its main" \
  'shadow: 1 merges, 1 records, 0 refused, 0 skipped, 0 drifted, 0 unreadable' "$fx/record-main-moved.json"
scores "a time that is not UTC to the second is refused" \
  'record 9001-1: unreadable: \.read: expected a time, YYYY-MM-DDTHH:MM:SSZ' \
  "$(edited bad-time '.read = "2026-11-14T13:37:13+00:00"')"
scores "a commit that is not 40 hexadecimal digits is refused" \
  'record 9001-1: unreadable: \.outcome\.trees\[0\]\.tree: expected a commit, 40 hexadecimal digits' \
  "$(edited bad-tree '.outcome.trees = [{commit: ("a" * 40), tree: "::error::x"}]')"
scores "a trigger of an unknown kind is refused" \
  'record 9001-1: unreadable: \.trigger\.kind: "schedule" is not a trigger' \
  "$(edited bad-trigger '.trigger = {kind: "schedule"}')"
scores "an outcome of an unknown kind is refused" \
  'record 9001-1: unreadable: \.outcome\.kind: "late" is not an outcome' \
  "$(edited bad-outcome '.outcome.kind = "late"')"
scores "the runs of each trigger are counted" \
  'runs: mainMoved 1, gateDone 2 \(cancelled 1\), comment 1, dispatch 1; 0 superseded while pending, 0 skipped by the filter' \
  "$idle" "$(edited t1 '.trigger = {kind: "mainMoved"}')" \
  "$(edited t2 '.trigger = {kind: "gateDone", head: ("a" * 40), conclusion: "cancelled"}')" \
  "$(edited t3 '.trigger = {kind: "gateDone", head: ("a" * 40), conclusion: "success"}')" \
  "$(edited t4 '.trigger = {kind: "comment", pr: 257, id: 9}')"

scores "the merges line counts the word assumed for the one seat that reads one word away" \
  'merges: agrees 0, waits 1, disagrees 0, other tree 0, blind 0; a word was assumed for 1; no author 0; updater pushes 2' \
  "$idle"
r302="$fx/window/records/1002-1.json"
m302=$(jq -c 'map(select(.pr == 302))' "$fx/window/merges.json")
scores "a push that two records plan is counted once" \
  'pushes: the updater started 0 ci runs; the plans name 1 distinct pushes' "$r302" "$r302"
RUNS='[{"id": 9001, "conclusion": "cancelled"}, {"id": 9100, "conclusion": "cancelled"}]' \
  scores "a cancelled run that left a record was not superseded while pending" \
  'runs: .*; 1 superseded while pending, 0 skipped by the filter' "$idle"
MERGES=$m302 scores "the control: a replay whose tree merged agrees" \
  '#302 at f302f30: agrees\. awaitPush; its replay merged; record of run 9001, 30 s old; 2 updater pushes' \
  "$r302"
MERGES=$m302 scores "a replay whose tree the record did not read is blind, not another tree" \
  '#302 at f302f30: blind\. awaitPush; another head merged; record of run 9001, 30 s old; 2 updater pushes' \
  "$(jq -c '.outcome.trees = []' "$r302" >"$tmp/no-tree.json"; echo "$tmp/no-tree.json")"
MERGES=$m302 scores "a tree the record read for another commit is not the replay's" \
  '#302 at f302f30: blind\. .*' \
  "$(jq -c '.outcome.trees[0].commit = ("b" * 40)' "$r302" >"$tmp/other-commit.json"; echo "$tmp/other-commit.json")"
MERGES=$(jq -c '.[0].tree = ""' <<<"$m302") scores "a merge whose tree was not read is blind, not another tree" \
  '#302 at f302f30: blind\. .*' "$r302"
MERGES=$(jq -c '.[0].tree = ("e" * 40)' <<<"$m302") scores "a replay whose tree did not merge is another tree" \
  '#302 at f302f30: other tree\. awaitPush; another tree merged; .*' "$r302"

window "$tmp/w"
cp "$idle" "$tmp/w/records/999-1.json"
cp "$idle" "$tmp/w/records/1000-1.json"
got=0
"$bin" shadow "$tmp/w" >"$tmp/out" 2>"$tmp/err" || got=$?
if [ "$got" = 0 ] && grep -qxE '#257 at d7616ac: waits\. .*; record of run 1000, 5 s old; .*' "$tmp/out"; then
  ok "of two records read in one second, the later run is used, whatever the file order"
else
  bad "of two records read in one second, the later run is used, whatever the file order" \
    "exit $got: $(cat "$tmp/err")" "$(cat "$tmp/out")"
fi

window "$tmp/w" "$idle"
mv "$tmp/w/records/9001-1.json" "$tmp/w/records/latest.json"
got=0
"$bin" shadow "$tmp/w" >"$tmp/out" 2>&1 || got=$?
if [ "$got" = 0 ] && grep -qx 'record latest: unreadable: the name is not <run>-<attempt>.json' "$tmp/out"; then
  ok "a record file not named by its run is listed"
else
  bad "a record file not named by its run is listed" "exit $got" "$(cat "$tmp/out")"
fi

errs() {
  local name=$1 pat=$2 got=0
  "$bin" shadow "$tmp/w" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" = 1 ] && [ ! -s "$tmp/out" ] && [ "$(grep -c '' "$tmp/err")" = 1 ] \
    && grep -qxE -- "shadow: $pat" "$tmp/err"; then
    ok "$name"
  else
    bad "$name" "exit $got, stdout: $(cat "$tmp/out")" "stderr: $(cat "$tmp/err")" "want: $pat"
  fi
}
review_window() {
  window "$tmp/w" "$idle"
  jq --argjson reviews "$1" --argjson comments "$2" \
    '.[0].reviews=$reviews | .[0].reviewComments=$comments' "$tmp/w/merges.json" >"$tmp/m"
  mv "$tmp/m" "$tmp/w/merges.json"
}
summary_result() {
  local name=$1 summary=$2 got=0
  "$bin" shadow "$tmp/w" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" = 0 ] && [ ! -s "$tmp/err" ] &&
      { if [ "$summary" = spoke ]; then
          grep -q 'disagrees\. stop noEntry' "$tmp/out" && ! grep -q 'one word away' "$tmp/out"
        else grep -q 'one word away' "$tmp/out"; fi; }; then ok "$name"
  else bad "$name" "exit $got: $(cat "$tmp/err")" "$(cat "$tmp/out")"; fi
}
for input in reviews reviewComments; do
  for invalid in missing null '{}' 7 '"wrong"'; do
    review_window '[]' '[]'
    if [ "$invalid" = missing ]; then
      jq --arg k "$input" '.[0] |= del(.[$k])' "$tmp/w/merges.json" >"$tmp/m"
    else
      jq --arg k "$input" --argjson v "$invalid" '.[0][$k]=$v' "$tmp/w/merges.json" >"$tmp/m"
    fi
    mv "$tmp/m" "$tmp/w/merges.json"
    errs "$input evidence $invalid refuses without favorable stdout" "merges\.json\[0\]\.$input: .*"
  done
done
for edit in 'del(.full_name)' '.full_name=null' '.full_name=""' '.full_name="owner"' \
    '.full_name="owner/a/b"' '.full_name="./mitos"' '.full_name="owner/.."' \
    '.full_name="other/mitos"' '.owner=null' 'del(.owner.login)' '.owner.login=null' \
    '.owner.login=""' '.owner.login="."' '.owner.login=".."' '.owner.login="bad/name"'; do
  window "$tmp/w" "$idle"
  jq "$edit" "$tmp/w/repo.json" >"$tmp/m"; mv "$tmp/m" "$tmp/w/repo.json"
  errs "repository evidence $edit refuses" 'repo\.json.*'
done
window "$tmp/w" "$idle"
rm "$tmp/w/repo.json"
errs "missing repository evidence refuses" 'repo\.json is missing'
review_window '[]' '[]'
echo '{"full_name":"OwNeR/Mitos","owner":{"login":"owner"}}' >"$tmp/w/repo.json"
summary_result "repository owner agreement is case-insensitive" silent
owner_review=$(jq -cn --arg h "$head257" '[{id:4,user:{login:"owner"},state:"COMMENTED",commit_id:$h,
  submitted_at:"2026-11-14T13:30:00Z",body:""}]')
footer_comment=$(jq -cn '[{pull_request_review_id:4,user:{login:"owner"},created_at:"2026-11-14T13:30:30Z",
  updated_at:"2026-11-14T13:30:30Z",body:"Replied.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"}]')
review_window "$(jq '.[0].user.login="OwNeR"' <<<"$owner_review")" '[]'
echo '{"full_name":"owner/mitos","owner":{"login":"OwNeR"}}' >"$tmp/w/repo.json"
summary_result "repository evidence preserves the canonical login spelling" spoke
review_window "$(jq '.[0].user.login="org_.1"' <<<"$owner_review")" '[]'
echo '{"full_name":"org_.1/repo_.1","owner":{"login":"org_.1"}}' >"$tmp/w/repo.json"
summary_result "repository evidence accepts the existing route-component grammar" spoke
review_window "$owner_review" "$footer_comment"
summary_result "a matching footer is silent before its deletion" silent
review_window "$owner_review" '[]'
summary_result "deleting that matching footer restores the postless blocker" spoke
review_window "$owner_review" "$(jq '.[0].pull_request_review_id=5' <<<"$footer_comment")"
summary_result "a footer for another review does not spare the owner review" spoke
review_window "$(jq '.[0].user.login="someone"' <<<"$owner_review")" '[]'
summary_result "a nonowner review is not an owner blocker" silent
review_window "$(jq '.[0].body=null' <<<"$owner_review")" '[]'
summary_result "a null review body retains the shared empty-body behavior" spoke
review_window "$(jq '.[0].user=null' <<<"$owner_review")" '[]'
summary_result "a null review user retains the shared nonowner behavior" silent
review_window '[{"state":"PENDING"}]' '[]'
summary_result "pending reviews are omitted before retained-item decoding" silent
review_window "$owner_review" "$(jq '.[0] |= del(.pull_request_review_id)' <<<"$footer_comment")"
errs "a missing review-comment ID refuses" 'merges\.json\[0\]\.reviewComments: .*'
for time in 13:37:17 13:37:18 13:37:19; do
  expected=spoke; [ "$time" != 13:37:19 ] || expected=silent
  review_window "$(jq --arg t "2026-11-14T${time}Z" '.[0].submitted_at=$t' <<<"$owner_review")" '[]'
  summary_result "review submission $time has an inclusive merge cutoff" "$expected"
  expected=silent; [ "$time" != 13:37:19 ] || expected=spoke
  review_window "$owner_review" "$(jq --arg t "2026-11-14T${time}Z" '.[0].created_at=$t | .[0].updated_at=$t' <<<"$footer_comment")"
  summary_result "comment creation $time has an inclusive merge cutoff" "$expected"
done
review_window "$owner_review" "$(jq '.[0].updated_at="2099-11-14T13:30:30Z"' <<<"$footer_comment")"
summary_result "comment filtering uses creation rather than update time" silent
review_window "$(jq '.[0].submitted_at="2099-11-14T13:30:00Z" | .[0].body=7' <<<"$owner_review")" '[]'
errs "a malformed late review is decoded before time filtering" 'merges\.json\[0\]\.reviews: .*'
review_window "$owner_review" "$(jq '.[0].created_at="2099-11-14T13:30:30Z" | .[0].body=7' <<<"$footer_comment")"
errs "a malformed late review comment is decoded before time filtering" 'merges\.json\[0\]\.reviewComments: .*'

window "$tmp/w" "$idle"
rm "$tmp/w/merges.json"
errs "a missing file is exit 1" 'merges\.json is missing'
window "$tmp/w" "$idle"
echo '[{"pr": 1}]' >"$tmp/w/merges.json"
errs "a merge without a time is exit 1" 'merges\.json\[0\]\.time: missing'
window "$tmp/w" "$idle"
echo '[{"id": 1, "conclusion": "Cancelled"}]' >"$tmp/w/runs.json"
errs "a conclusion that is not one is exit 1" 'runs\.json\[0\]\.conclusion: expected 1 to 32 of a-z and _'
window "$tmp/w" "$idle"
echo '{' >"$tmp/w/baseline.json"
errs "a file that is not JSON is exit 1" 'baseline\.json is not JSON: .*'
window "$tmp/w" "$idle"
rm -r "$tmp/w/records"
errs "a folder without records/ is exit 1" 'records/ is missing'
got=0
"$bin" shadow >"$tmp/out" 2>"$tmp/err" || got=$?
if [ "$got" = 2 ] && [ ! -s "$tmp/out" ]; then ok "no argument is a usage error"; else bad "no argument is a usage error" "exit $got"; fi

day=$(date -u +%F)
art="$tmp/art"
mkdir -p "$art"
jq -c '.trigger = {kind: "mainMoved"}' "$idle" >"$art/record.json"
(cd "$art" && zip -q record.zip record.json) || { echo "FAIL zip"; exit 1; }
merge_sha=$(printf 'c%.0s' {1..40})
fake="$tmp/fake"
mkdir -p "$fake"
cat >"$fake/gh" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$FAKE_LOG"
if [ -n "${FAKE_FAIL:-}" ] && [[ $* == *"$FAKE_FAIL"* ]]; then exit 1; fi
run() { printf '{"id":%s,"run_attempt":1,"event":"push","conclusion":"%s","created_at":"x","run_started_at":"x","updated_at":"x"}' "$1" "$2"; }
case "$*" in
  "api repos/owner/mitos")
    if [ -n "${FAKE_METADATA+x}" ]; then printf '%s\n' "$FAKE_METADATA"
    else echo '{"full_name":"owner/mitos","owner":{"login":"owner"}}'; fi ;;
  "api repos/owner/mitos/pulls/257/reviews?per_page=100&page="* | "api repos/owner/mitos/pulls/257/comments?per_page=100&page="*)
    page=${2##*page=}
    route=reviews; [[ $2 != *"/comments?"* ]] || route=comments
    if [ -n "${FAKE_REVIEW_PAGES:-}" ] && [ -f "$FAKE_REVIEW_PAGES/$route-$page.json" ]; then
      cat "$FAKE_REVIEW_PAGES/$route-$page.json"
    else echo '[]'; fi ;;
  *"actions/workflows/land.yml/runs"*"&page=1")
    printf '{"workflow_runs":['
    for i in $(seq 8001 8099); do run "$i" skipped; printf ','; done
    run 8100 skipped
    printf ']}' ;;
  *"actions/workflows/land.yml/runs"*"&page=2")
    printf '{"workflow_runs":[%s,%s,%s]}' "$(run 9001 success)" "$(run 9002 cancelled)" "$(run 9003 skipped)" ;;
  *"actions/workflows/ci.yml/runs"*"&page=1")
    printf '{"workflow_runs":[{"id":1,"event":"pull_request","triggering_actor":{"login":"mitos-pr-updater[bot]"}},{"id":2,"event":"push","triggering_actor":null}]}' ;;
  *"artifacts?name=land-record-9001-1&"*)
    printf '{"total_count":3,"artifacts":[{"id":66,"expired":false,"workflow_run":{"id":4242}},{"id":55,"expired":true,"workflow_run":{"id":9001}},{"id":77,"expired":false,"workflow_run":{"id":9001}}]}' ;;
  *"artifacts?name="*) printf '{"total_count":0,"artifacts":[]}' ;;
  *"artifacts/77/zip"*) cat "$FAKE_ZIP" ;;
  *"pulls?state=closed"*"&page=1")
    printf '[{"number":257,"merged_at":"%sT23:59:59Z","updated_at":"%sT23:59:59Z","merge_commit_sha":"%s","head":{"sha":"%s"}},{"number":6,"merged_at":null,"updated_at":"%sT23:59:58Z","merge_commit_sha":null,"head":{"sha":"%s"}},{"number":5,"merged_at":"2000-01-01T00:00:00Z","updated_at":"2000-01-01T00:00:00Z","merge_commit_sha":"%s","head":{"sha":"%s"}}]' \
      "$FAKE_DAY" "$FAKE_DAY" "$FAKE_MERGE" "$FAKE_HEAD" "$FAKE_DAY" "$FAKE_HEAD" "$FAKE_MERGE" "$FAKE_HEAD" ;;
  "api -i repos/"*"/activity?ref=refs/heads/main&direction=desc&per_page=100")
    printf 'HTTP/1.1 200 OK\r\nLink: <https://api.github.com/repositories/1/activity?ref=refs%%2Fheads%%2Fmain&per_page=100&after=Y3Vy_c29y-1>; rel="next"\r\n\r\n'
    printf '[{"before":"x1","after":"x2","timestamp":"%sT23:59:59Z"}]' "$FAKE_DAY" ;;
  "api -i repos/"*"/activity?ref=refs/heads/main&direction=desc&per_page=100&after=Y3Vy_c29y-1")
    printf 'HTTP/1.1 200 OK\r\nLink: <https://api.github.com/repositories/1/activity?ref=refs%%2Fheads%%2Fmain&per_page=100&after=Zm9v-2>; rel="next"\r\n\r\n'
    printf '[{"before":"%s","after":"%s","timestamp":"%sT23:59:59Z"},{"before":"x","after":"y","timestamp":"2000-01-01T00:00:00Z"}]' \
      "$FAKE_MAIN" "$FAKE_MERGE" "$FAKE_DAY" ;;
  "api -i repos/"*"/activity?ref=refs/heads/main&direction=desc&per_page=100&after=Zm9v-2")
    printf 'HTTP/1.1 200 OK\r\n\r\n[]' ;;
  *"git/commits/"*)
    [ -n "${FAKE_BLOCK:-}" ] && mkdir -p "$FAKE_BLOCK"
    printf 'dddddddddddddddddddddddddddddddddddddddd\n' ;;
  *) exit 1 ;;
esac
EOF
chmod +x "$fake/gh"
cat >"$fake/timeout" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$FAKE_TIMEOUT_LOG"
exec "$REAL_TIMEOUT" "$@"
EOF
chmod +x "$fake/timeout"
real_timeout=$(command -v timeout)
fetch() {
  local got=0
  PATH="$fake:$PATH" FAKE_LOG="$tmp/gh.log" FAKE_ZIP="$art/record.zip" FAKE_DAY="$day" \
    FAKE_MERGE="$merge_sha" FAKE_HEAD="$head257" FAKE_MAIN="$main" \
    FAKE_TIMEOUT_LOG="$tmp/timeout.log" REAL_TIMEOUT="$real_timeout" \
    "$real_timeout" 60 "$root/gate/shadow-fetch.sh" "$@" >"$tmp/fetch.out" 2>"$tmp/fetch.err" || got=$?
  return "$got"
}
rm -f "$tmp/gh.log" "$tmp/timeout.log"
if fetch owner/mitos "$day" "$tmp/f"; then
  have=$(cd "$tmp/f" && find . -type f | sort | paste -sd' ' -)
  want="./baseline.json ./merges.json ./records/9001-1.json ./repo.json ./runs.json"
  if [ "$have" = "$want" ] && [ ! -s "$tmp/fetch.err" ]; then
    ok "fetch: one file per input, and one record per artifact"
  else
    bad "fetch: one file per input, and one record per artifact" "have: $have" "$(cat "$tmp/fetch.err")"
  fi
  want='[{"pr":257,"time":"'"$day"'T23:59:59Z","head":"'"$head257"'","before":"'"$main"'","tree":"dddddddddddddddddddddddddddddddddddddddd","reviews":[],"reviewComments":[]}]'
  if [ "$(jq -c . "$tmp/f/merges.json")" = "$want" ]; then
    ok "fetch: only the merges of the window, with main before and the tree"
  else
    bad "fetch: only the merges of the window, with main before and the tree" "$(cat "$tmp/f/merges.json")" "want: $want"
  fi
  if [ "$(jq -c 'map(.actor)' "$tmp/f/baseline.json")" = '["mitos-pr-updater[bot]",""]' ]; then
    ok "fetch: the baseline names who started each ci run"
  else
    bad "fetch: the baseline names who started each ci run" "$(cat "$tmp/f/baseline.json")"
  fi
  if grep -q "actions/workflows/land.yml/runs?created=$day&per_page=100&page=2" "$tmp/gh.log" \
    && ! grep -qi graphql "$tmp/gh.log" && [ "$(grep -c '^api ' "$tmp/gh.log")" = "$(grep -c '' "$tmp/gh.log")" ] \
    && ! grep -q 'land-record-9003' "$tmp/gh.log"; then
    ok "fetch: REST only, one day at a time, and no artifact read for a run the filter skipped"
  else
    bad "fetch: REST only, one day at a time, and no artifact read for a run the filter skipped" "$(cat "$tmp/gh.log")"
  fi
  if grep -q 'artifacts/77/zip' "$tmp/gh.log" && ! grep -qE 'artifacts/(55|66)/zip' "$tmp/gh.log"; then
    ok "fetch: only an unexpired artifact of the run itself is read"
  else
    bad "fetch: only an unexpired artifact of the run itself is read" "$(cat "$tmp/gh.log")"
  fi
  reads=$(grep -c '' "$tmp/gh.log")
  if [ "$reads" -gt 0 ] && [ "$(grep -c '^-k 5 120 gh api ' "$tmp/timeout.log")" = "$reads" ]; then
    ok "fetch: every read is bounded by a timeout"
  else
    bad "fetch: every read is bounded by a timeout" "$reads reads" "$(cat "$tmp/timeout.log")"
  fi
  if [ "$(jq length "$tmp/f/runs.json")" = 103 ] && ! grep -q -- '--paginate' "$tmp/gh.log" \
    && grep -q 'after=Y3Vy_c29y-1$' "$tmp/gh.log" && ! grep -q 'after=Zm9v-2' "$tmp/gh.log" \
    && ! grep -q 'page=2$' <(grep 'pulls?' "$tmp/gh.log"); then
    ok "fetch: pages by number and by cursor, and stops at the window"
  else
    bad "fetch: pages by number and by cursor, and stops at the window" "$(cat "$tmp/gh.log")"
  fi
  got=0
  "$bin" shadow "$tmp/f" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" = 0 ] && grep -qxE '#257 at d7616ac: waits\. .*record of run 9001, [0-9]+ s old.*' "$tmp/out" \
    && grep -qx 'runs: mainMoved 1, gateDone 0 (cancelled 0), comment 0, dispatch 0; 1 superseded while pending, 101 skipped by the filter' "$tmp/out" \
    && grep -qx 'pushes: the updater started 1 ci runs; the plans name 0 distinct pushes' "$tmp/out"; then
    ok "fetch: the folder it writes is one the scorer reads"
  else
    bad "fetch: the folder it writes is one the scorer reads" "exit $got: $(cat "$tmp/err")" "$(cat "$tmp/out")"
  fi
else
  bad "fetch: one file per input, and one record per artifact" "exit non-zero: $(cat "$tmp/fetch.err")"
fi
fails() {
  local what=$1 route=$2 got=0
  rm -rf "$tmp/g"
  FAKE_FAIL=$route fetch owner/mitos "$day" "$tmp/g" || got=$?
  if [ "$got" = 1 ] && [ "$(cat "$tmp/fetch.err")" = "shadow-fetch: the read of $what failed" ]; then
    ok "fetch: a failed read of $what is exit 1, with one line"
  else
    bad "fetch: a failed read of $what is exit 1, with one line" "exit $got: $(cat "$tmp/fetch.err")"
  fi
}
fails "the activity of main" '/activity?'
fails "the runs of land.yml on $day" "land.yml/runs?created=$day&per_page=100&page=2"
fails "the artifacts named land-record-9001-1" 'artifacts?name=land-record-9001-1&'
fails "the commit $merge_sha" 'git/commits/'
fails "the repository" 'api repos/owner/mitos'
fails "the reviews of #257" 'pulls/257/reviews?'
fails "the review comments of #257" 'pulls/257/comments?'
valid_metadata='{"full_name":"owner/mitos","owner":{"login":"owner"}}'
other_metadata='{"full_name":"elsewhere/mitos","owner":{"login":"elsewhere"}}'
for metadata in '{"full_name":"elsewhere/mitos","owner":{"login":"elsewhere"}}' \
    '{"full_name":"owner/mitos","owner":{"login":""}}' \
    '{"full_name":"owner/mitos","owner":{"login":"other"}}' \
    "$(printf '%s\n%s' "$other_metadata" "$valid_metadata")" \
    "$(printf '%s\n%s' "$valid_metadata" "$other_metadata")" \
    "$(printf '%s\n%s' "$valid_metadata" "$valid_metadata")"; do
  rm -rf "$tmp/meta"
  got=0; FAKE_METADATA="$metadata" fetch owner/mitos "$day" "$tmp/meta" || got=$?
  if [ "$got" = 1 ] && [ ! -s "$tmp/fetch.out" ] &&
      [ "$(cat "$tmp/fetch.err")" = 'shadow-fetch: the read of the repository failed' ] &&
      [ ! -e "$tmp/meta/merges.json" ]; then
    ok "fetch: invalid repository binding refuses"
  else bad "fetch: invalid repository binding refuses" "exit $got: $(cat "$tmp/fetch.err")"; fi
done
rm -rf "$tmp/case-meta"
if FAKE_METADATA='{"full_name":"OWNER/Mitos","owner":{"login":"owner"}}' \
    fetch owner/mitos "$day" "$tmp/case-meta" &&
    jq -e -s 'length==1 and (.[0]|type=="object")' "$tmp/case-meta/repo.json" >/dev/null &&
    "$bin" shadow "$tmp/case-meta" >"$tmp/out" 2>"$tmp/err"; then
  ok "fetch: one canonical repository object is usable and case-insensitive"
else bad "fetch: one canonical repository object is usable and case-insensitive" "$(cat "$tmp/fetch.err" "$tmp/err")"; fi
pages="$tmp/route-pages"
mkdir -p "$pages"
jq -n --arg h "$head257" '[range(1;101)|{id:.,user:{login:"other"},state:"COMMENTED",commit_id:$h,
  submitted_at:"2000-01-01T00:00:00Z",body:""}]' >"$tmp/neutral-reviews.json"
jq -n '[range(1;101)|{pull_request_review_id:5,user:{login:"other"},created_at:"2000-01-01T00:00:00Z",
  updated_at:"2000-01-01T00:00:00Z",body:"old"}]' >"$tmp/neutral-comments.json"
for route in reviews comments; do
  for page in 1 2; do
    for invalid in '{}' null 7 stream; do
      rm -f "$pages"/*.json
      if [ "$page" = 2 ]; then cp "$tmp/neutral-$route.json" "$pages/$route-1.json"; fi
      if [ "$invalid" = stream ]; then printf '[]\n[]\n' >"$pages/$route-$page.json"
      else printf '%s\n' "$invalid" >"$pages/$route-$page.json"; fi
      rm -rf "$tmp/page-failure"
      got=0; FAKE_REVIEW_PAGES="$pages" fetch owner/mitos "$day" "$tmp/page-failure" || got=$?
      if [ "$got" = 1 ] && [ ! -s "$tmp/fetch.out" ] && [ ! -e "$tmp/page-failure/merges.json" ] &&
          [ "$(grep -c '' "$tmp/fetch.err")" = 1 ]; then
        ok "fetch: $route page $page requires one array ($invalid)"
      else bad "fetch: $route page $page requires one array ($invalid)" "exit $got: $(cat "$tmp/fetch.err")"; fi
    done
  done
done
rm -f "$pages"/*.json
cp "$tmp/neutral-reviews.json" "$pages/reviews-1.json"
jq -n --arg h "$head257" --arg day "$day" '[{id:4,user:{login:"owner"},state:"COMMENTED",commit_id:$h,
  submitted_at:($day+"T13:30:00Z"),body:""}]' >"$pages/reviews-2.json"
rm -rf "$tmp/page-blocker"
if FAKE_REVIEW_PAGES="$pages" fetch owner/mitos "$day" "$tmp/page-blocker" &&
    [ "$(jq '.[0].reviews|length' "$tmp/page-blocker/merges.json")" = 101 ] &&
    "$bin" shadow "$tmp/page-blocker" >"$tmp/out" 2>"$tmp/err" &&
    grep -q 'disagrees\. stop noEntry' "$tmp/out"; then
  ok "fetch: only a later review page supplies the owner blocker"
else bad "fetch: only a later review page supplies the owner blocker" "$(cat "$tmp/fetch.err" "$tmp/out" "$tmp/err")"; fi
rm -f "$pages/reviews-1.json"
mv "$pages/reviews-2.json" "$pages/reviews-1.json"
cp "$tmp/neutral-comments.json" "$pages/comments-1.json"
jq --arg day "$day" '.[0].created_at=($day+"T13:30:30Z") | .[0].updated_at=($day+"T13:30:30Z")' \
  <<<"$footer_comment" >"$pages/comments-2.json"
rm -rf "$tmp/page-footer"
if FAKE_REVIEW_PAGES="$pages" fetch owner/mitos "$day" "$tmp/page-footer" &&
    [ "$(jq '.[0].reviewComments|length' "$tmp/page-footer/merges.json")" = 101 ] &&
    "$bin" shadow "$tmp/page-footer" >"$tmp/out" 2>"$tmp/err" && grep -q 'one word away' "$tmp/out"; then
  ok "fetch: only a later comment page supplies the matching footer"
else bad "fetch: only a later comment page supplies the matching footer" "$(cat "$tmp/fetch.err" "$tmp/out" "$tmp/err")"; fi
echo '[]' >"$pages/comments-2.json"
rm -rf "$tmp/page-deleted"
if FAKE_REVIEW_PAGES="$pages" fetch owner/mitos "$day" "$tmp/page-deleted" &&
    "$bin" shadow "$tmp/page-deleted" >"$tmp/out" 2>"$tmp/err" &&
    grep -q 'disagrees\. stop noEntry' "$tmp/out"; then
  ok "fetch: removing the later-page footer restores the blocker"
else bad "fetch: removing the later-page footer restores the blocker" "$(cat "$tmp/fetch.err" "$tmp/out" "$tmp/err")"; fi
for route in reviews comments; do
  rm -f "$pages"/*.json
  cp "$tmp/neutral-$route.json" "$pages/$route-1.json"
  FAKE_REVIEW_PAGES="$pages" fails "$(if [ "$route" = reviews ]; then echo 'the reviews of #257'; else echo 'the review comments of #257'; fi)" \
    "pulls/257/$route?per_page=100&page=2"
done

got=0
FAKE_BLOCK="$tmp/k/merges.json" fetch owner/mitos "$day" "$tmp/k" || got=$?
if [ "$got" = 1 ] && [ "$(cat "$tmp/fetch.err")" = 'shadow-fetch: merges.json was not written' ]; then
  ok "fetch: a write that fails is exit 1, with one line"
else
  bad "fetch: a write that fails is exit 1, with one line" "exit $got: $(cat "$tmp/fetch.err")"
fi
refuses() {
  local args="$*"
  if fetch "$@"; then
    bad "fetch refuses: $args" "exit 0"
  elif [ "$(grep -c '' "$tmp/fetch.err")" = 1 ] && grep -q '^shadow-fetch: ' "$tmp/fetch.err"; then
    ok "fetch refuses: ${args//$tmp/<tmp>}"
  else
    bad "fetch refuses: $args" "$(cat "$tmp/fetch.err")"
  fi
}
refuses owner/mitos "$day"
refuses owner "$day" "$tmp/h"
refuses owner/.. "$day" "$tmp/h"
refuses owner/mitos 2026-02-30 "$tmp/h"
refuses owner/mitos "$(date -u -d tomorrow +%F)" "$tmp/h"
refuses owner/mitos "$day" "$tmp/f"
for invalid_repo in ./mitos ../mitos owner/. owner/..; do
  rm -f "$tmp/gh.log"
  got=0; fetch "$invalid_repo" "$day" "$tmp/invalid-route" || got=$?
  if [ "$got" = 2 ] && [ ! -s "$tmp/gh.log" ] && [ ! -s "$tmp/fetch.out" ] &&
      [ "$(cat "$tmp/fetch.err")" = 'shadow-fetch: <owner/name> is not a repository name' ]; then
    ok "fetch: $invalid_repo refuses before any API call"
  else bad "fetch: $invalid_repo refuses before any API call" "exit $got: $(cat "$tmp/fetch.err")"; fi
done

echo
echo "$pass passed, $fail failed"
[ "$fail" = 0 ]
