#!/usr/bin/env bash
set -u

root=$(cd "$(dirname "$0")/.." && pwd)
(cd "$root" && lake build mitos-gate >/dev/null) || { echo "FAIL lake build mitos-gate"; exit 1; }
bin="$root/.lake/build/bin/mitos-gate"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

pass=0
fail=0
ok() { echo "ok   $1"; pass=$((pass + 1)); }
bad() {
  echo "FAIL $1"
  shift
  for l in "$@"; do echo "  | $l"; done
  fail=$((fail + 1))
}

hA=a1b2c3d0aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
hB=a1b2c3d1bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb
hC=c0ffee00cccccccccccccccccccccccccccccccc
footer='\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
printf '%s\t%s\t%s\t%s\t%s\n' \
  2026-11-13T12:00:06Z force_push owner "$hB" "$hC" \
  2026-11-13T12:00:04Z push owner "$hA" "$hB" \
  2026-11-13T12:00:02Z branch_creation owner 0000000000000000000000000000000000000000 "$hA" \
  >"$tmp/pushes.tsv"

# comment <id> <login> <slug or null> <created second> <updated second> <body as a JSON string>
comment() {
  local slug=null
  [ "$3" != null ] && slug="{\"slug\":\"$3\"}"
  printf '{"id":%s,"user":{"login":"%s"},"performed_via_github_app":%s,"created_at":"2026-11-13T12:00:%02dZ","updated_at":"2026-11-13T12:00:%02dZ","body":%s}' \
    "$1" "$2" "$slug" "$4" "$5" "$6"
}

# reads <name> <want stdout> <comment>... : exit 0 and exactly that output, with the pushes
reads() {
  local name=$1 want=$2 got=0
  shift 2
  (IFS=,; echo "[$*]") >"$tmp/in.json"
  "$bin" speech --owner owner --pr 7 --pushes "$tmp/pushes.tsv" "$tmp/in.json" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" != 0 ]; then bad "$name" "exit $got, expected 0" "$(cat "$tmp/err")"; return; fi
  if [ "$(cat "$tmp/out")" != "$(printf '%b' "$want")" ]; then
    bad "$name" "got:  $(cat "$tmp/out")" "want: $(printf '%b' "$want")"
    return
  fi
  ok "$name"
}

# refuses <name> <exit> <stderr pattern> <args>... : that exit, no stdout, one stderr line
refuses() {
  local name=$1 want=$2 pat=$3 got=0
  shift 3
  "$bin" speech "$@" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" != "$want" ] || [ -s "$tmp/out" ]; then
    bad "$name" "exit $got (expected $want), stdout: $(cat "$tmp/out")"
    return
  fi
  if ! head -n 1 "$tmp/err" | grep -qE -- "$pat"; then
    bad "$name" "stderr: $(cat "$tmp/err")" "want:   $pat"
    return
  fi
  if [ "$want" = 1 ] && [ "$(grep -c '' "$tmp/err")" != 1 ]; then
    bad "$name" "stderr is not one line: $(cat "$tmp/err")"
    return
  fi
  ok "$name"
}

reads "a typed /land names the head of its second" "112 ownerLand@224 $hC land" \
  "$(comment 112 owner null 12 12 '"/land"')"
reads "a /land between two pushes names the head then" "105 ownerLand@210 $hB land" \
  "$(comment 105 owner null 5 5 '"/land"')"
reads "an app's /land is no word" "112 ignored app-post-without-record" \
  "$(comment 112 owner claude 12 12 '"/land"')"
reads "a Grok relay's /land is no word" "112 ignored app-post-without-record" \
  "$(comment 112 owner cursor 12 12 '"/land"')"
reads "another login prints nothing" "" "$(comment 112 someone null 12 12 '"/land"')"
reads "an edited comment holds above every comment of the edit's second" \
  "101 ownerHold@221 edited\n110 ownerLand@220 $hC land" \
  "$(comment 101 owner null 1 10 '"hello"')" "$(comment 110 owner null 10 10 '"/land"')"
reads "an edited app post holds" "112 ownerHold@225 edited" \
  "$(comment 112 owner claude 12 13 '"notes"')"
reads "a typed post with a trailing footer is no word" "112 ignored footer" \
  "$(comment 112 owner null 12 12 "\"/land$footer\"")"
reads "a quoted footer is still the owner's text" "112 ignored no-word" \
  "$(comment 112 owner null 12 12 '"> ---\n> _Generated by [Claude Code](https://claude.ai/code)_\n\n@claude yes"')"
reads "CRLF line ends" "112 ownerLand@224 $hC land" \
  "$(comment 112 owner null 12 12 '"please land\r\n/land\r\n"')"
reads "a quoted, fenced or indented /land is no word" \
  "112 ignored no-word\n113 ignored no-word\n114 ignored no-word" \
  "$(comment 112 owner null 12 12 '"> /land"')" "$(comment 113 owner null 13 13 '"~~~\n/land\n~~~"')" \
  "$(comment 114 owner null 14 14 '"    /land"')"
reads "a fence inside a list item holds a /land" "112 ownerHold@224 fence-or-html-in-the-comment" \
  "$(comment 112 owner null 12 12 '"- ~~~\n  /land\n  ~~~"')"
reads "a /land carrying on a quote holds" "112 ownerHold@224 inside-a-quote" \
  "$(comment 112 owner null 12 12 '"> example\n/land"')"
reads "a code span across lines holds a /land" "112 ownerHold@224 fence-or-html-in-the-comment" \
  "$(comment 112 owner null 12 12 "\"\`example\\n/land \\n\`\"")"
reads "a quoted /hold holds" "112 ownerHold@224 hold" "$(comment 112 owner null 12 12 '"> /hold"')"
reads "a lone CR ends a line" "112 ownerHold@224 hold" \
  "$(comment 112 owner null 12 12 '"notes\r/hold"')"
reads "a unique prefix resolves" "112 ownerLand@224 $hB land" \
  "$(comment 112 owner null 12 12 '"/land a1b2c3d1"')"
reads "an ambiguous prefix holds" "112 ownerHold@224 ambiguous-commit" \
  "$(comment 112 owner null 12 12 '"/land a1b2c3d"')"
reads "two word lines hold" "112 ownerHold@224 several-words" \
  "$(comment 112 owner null 12 12 '"/land\n/hold"')"
reads "a /land in a push's second holds" "104 ownerHold@208 no-head-at-that-second" \
  "$(comment 104 owner null 4 4 '"/land"')"
reads "an agent's land record from its own app" "112 agentLand@224 claude \"worker\" $hC record" \
  "$(comment 112 owner claude 12 12 "\"\`\`\`mitos-protocol\n{\\\"v\\\":1,\\\"kind\\\":\\\"land\\\",\\\"task\\\":7,\\\"as\\\":{\\\"provider\\\":\\\"claude\\\",\\\"teammate\\\":\\\"worker\\\"},\\\"head\\\":\\\"$hC\\\"}\n\`\`\`$footer\"")"
reads "a record with a duplicate key is malformed" "112 ignored malformed-record" \
  "$(comment 112 owner claude 12 12 "\"\`\`\`mitos-protocol\n{\\\"v\\\":1,\\\"kind\\\":\\\"land\\\",\\\"task\\\":8,\\\"task\\\":7,\\\"as\\\":{\\\"provider\\\":\\\"claude\\\",\\\"teammate\\\":\\\"worker\\\"},\\\"head\\\":\\\"$hC\\\"}\n\`\`\`$footer\"")"
reads "a teammate name holding a workflow command marker is escaped" \
  "112 agentLand@224 claude \"##\\\\u{005B}error]x\" $hC record" \
  "$(comment 112 owner claude 12 12 "\"\`\`\`mitos-protocol\n{\\\"v\\\":1,\\\"kind\\\":\\\"land\\\",\\\"task\\\":7,\\\"as\\\":{\\\"provider\\\":\\\"claude\\\",\\\"teammate\\\":\\\"##[error]x\\\"},\\\"head\\\":\\\"$hC\\\"}\n\`\`\`\"")"

"$bin" speech --owner owner --pr 7 <(echo "[$(comment 112 owner null 12 12 '"/land"')]") \
  >"$tmp/out" 2>"$tmp/err" || true
if [ "$(cat "$tmp/out")" = "112 ownerHold@224 no-head-at-that-second" ]; then
  ok "without --pushes a bare /land has no head"
else
  bad "without --pushes a bare /land has no head" "got: $(cat "$tmp/out") $(cat "$tmp/err")"
fi

echo "[$(comment 112 owner null 12 12 '"/land"')]" >"$tmp/good.json"
echo '[{"id":1,"user":{"login":"owner"},"created_at":"2026-11-13T12:00:01Z","updated_at":"2026-11-13T12:00:01Z","body":"/land"}]' >"$tmp/noapp.json"
echo '[{"id":1,"user":{"login":"owner"},"performed_via_github_app":null,"created_at":"2026-11-13 12:00:01","updated_at":"2026-11-13T12:00:01Z","body":"/land"}]' >"$tmp/stamp.json"
echo '[{"id":1,"user":{"login":"owner"},"performed_via_github_app":null,"created_at":"2026-11-13T12:00:01Z","updated_at":"2026-11-13T12:00:01Z","body":null}]' >"$tmp/nobody.json"
echo '{"id":1}' >"$tmp/object.json"
echo '[{' >"$tmp/cut.json"
printf 'not\ta push\n' >"$tmp/badpushes.tsv"

refuses "a comment without performed_via_github_app is refused" 1 \
  '^speech: the comments are refused: \[0\]\.performed_via_github_app: missing$' \
  --owner owner --pr 7 "$tmp/noapp.json"
refuses "a timestamp of another shape is refused" 1 \
  '^speech: the comments are refused: \[0\]\.created_at: expected YYYY-MM-DDTHH:MM:SSZ$' \
  --owner owner --pr 7 "$tmp/stamp.json"
refuses "a null body is refused" 1 '^speech: the comments are refused: \[0\]\.body: expected a string$' \
  --owner owner --pr 7 "$tmp/nobody.json"
refuses "an object is not a list of comments" 1 '^speech: the comments are refused: expected a list' \
  --owner owner --pr 7 "$tmp/object.json"
refuses "cut JSON is refused" 1 '^speech: the comments are refused: not JSON' \
  --owner owner --pr 7 "$tmp/cut.json"
refuses "a line that is not a push is refused" 1 '^speech: the pushes are refused: ' \
  --owner owner --pr 7 --pushes "$tmp/badpushes.tsv" "$tmp/good.json"
refuses "a missing file is an I/O error" 1 '^speech: stopped on an I/O error' \
  --owner owner --pr 7 "$tmp/none.json"
refuses "no arguments is a usage error" 2 '^speech needs'
refuses "--pr must be a number" 2 '^speech needs' --owner owner --pr seven "$tmp/good.json"
refuses "--owner is needed" 2 '^speech needs' --pr 7 "$tmp/good.json"
refuses "one comments file" 2 '^speech needs' --owner owner --pr 7 "$tmp/good.json" "$tmp/good.json"
refuses "an unknown flag is a usage error" 2 '^speech needs' --owner owner --pr 7 --head x "$tmp/good.json"

echo "$pass passed, $fail failed"
[ "$fail" = 0 ]
