#!/usr/bin/env bash
set -u

root=$(cd "$(dirname "$0")/.." && pwd)
(cd "$root" && lake build mitos-gate >/dev/null) || { echo "FAIL lake build mitos-gate"; exit 1; }
bin="$root/.lake/build/bin/mitos-gate"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

pass=0
fail=0
ok() { echo "ok   $1"; pass=$((pass + 1)); }
bad() {
  echo "FAIL $1"
  shift
  for l in "$@"; do echo "  | $l"; done
  fail=$((fail + 1))
}

repo="$tmp/repo"
g() { git -C "$repo" -c user.name=test -c user.email=test@example.invalid -c commit.gpgsign=false "$@"; }
mkdir -p "$repo"
g init -q -b main
seq 1 30 >"$repo/a.txt"
g add -A
g commit -qm M1
m1=$(g rev-parse HEAD)
g checkout -qb pr
sed -i '1s/.*/one/' "$repo/a.txt"
g commit -qam P1
p1=$(g rev-parse HEAD)
g checkout -qb conflict "$m1"
sed -i '30s/.*/thirty-c/' "$repo/a.txt"
g commit -qam C1
c1=$(g rev-parse HEAD)
g checkout -q main
sed -i '30s/.*/thirty/' "$repo/a.txt"
g commit -qam M2
m2=$(g rev-parse HEAD)
g checkout -qb current
echo b >"$repo/b.txt"
g add -A
g commit -qm Q1
q1=$(g rev-parse HEAD)
g checkout -q --detach "$p1"
g rebase -q main
rebased=$(g rev-parse 'HEAD^{tree}')
g checkout -q main

zero=0000000000000000000000000000000000000000
body=$(printf 'Why.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_')
b="$tmp/base"
mkdir -p "$b"
echo '{"full_name":"owner/mitos","owner":{"login":"owner"}}' >"$b/repo.json"
pr_json() {
  jq -n --argjson n "$1" --arg sha "$2" --arg ref "$3" --arg body "$body" \
    '{number: $n, state: "open", draft: false, labels: [], body: $body,
      head: {sha: $sha, ref: $ref, repo: {full_name: "owner/mitos"}},
      base: {ref: "main", repo: {full_name: "owner/mitos"}}}'
}
jq -n --argjson a "$(pr_json 7 "$p1" pr)" --argjson c "$(pr_json 8 "$c1" conflict)" \
  --argjson q "$(pr_json 9 "$q1" current)" '[[$a, $c, $q]]' >"$b/open.json"
jq -n --arg s "$m2" '{commit: {sha: $s}}' >"$b/main.json"
echo '{"enforce_admins":{"enabled":true},"required_status_checks":{"strict":true,"contexts":["gate"],"checks":[{"context":"gate","app_id":15368}]}}' \
  >"$b/protection.json"
echo '[[]]' >"$b/stacks.json"
# shellcheck disable=SC2016
row() { printf '| #%s x | `%s` | green | PASS opus-xhigh at `%s`, author sonnet |\n' "$1" "${2:0:7}" "${2:0:7}"; }
dash_body() {
  # shellcheck disable=SC2016
  printf '## Needs you\n\n- nothing\n\n## In flight\n\n| PR | Head | `gate` | Verdict |\n|---|---|---|---|\n%s\n\n## Next up\n' \
    "$(row 7 "$p1"; row 8 "$c1"; row 9 "$q1"; printf "%s" "${1:-}")"
}
jq -n --arg body "$(dash_body)" \
  '{title: "Owner dashboard", user: {login: "owner"}, state: "open", body: $body}' >"$b/dashboard.json"
per_pr() {
  local n=$1 h=$2 file=$3
  jq -n --argjson id "${n}001" \
    '[[{id: $id, user: {login: "owner"}, performed_via_github_app: null,
        created_at: "2026-11-14T08:00:00Z", updated_at: "2026-11-14T08:00:00Z", body: "/land"}]]' \
    >"$b/comments-$n.json"
  echo '[[]]' >"$b/review-comments-$n.json"
  jq -n --arg h "$h" '[[{id: 1, user: {login: "coderabbitai[bot]"}, state: "COMMENTED",
      commit_id: $h, submitted_at: "2026-11-14T07:30:00Z", body: "Review."}]]' >"$b/reviews-$n.json"
  jq -n --arg f "$file" '[[{filename: $f}]]' >"$b/files-$n.json"
  jq -n --arg h "$h" '[{total_count: 1, check_runs: [{id: 10, name: "gate",
      app: {slug: "github-actions"}, head_sha: $h, status: "completed", conclusion: "success"}]}]' \
    >"$b/checks-$n.json"
  jq -n --arg h "$h" --arg z "$zero" '[[{timestamp: "2026-11-14T07:00:00Z",
      activity_type: "branch_creation", actor: {login: "owner"}, before: $z, after: $h}]]' \
    >"$b/activity-$n.json"
}
per_pr 7 "$p1" a.txt
per_pr 8 "$c1" a.txt
per_pr 9 "$q1" b.txt

d="$tmp/d"
fresh() { rm -rf "$d"; cp -r "$b" "$d"; }
snap() {
  local got=0
  (cd "$repo" && "$bin" snapshot "$d") >"$tmp/snap.json" 2>"$tmp/snap.err" || got=$?
  return "$got"
}
me7='. + {me: {provider: "claude", name: "orchestrator"}, pr: 7}'
decide() {
  local got=0
  jq -c "$1" "$tmp/snap.json" | "$bin" land >"$tmp/land.out" 2>"$tmp/land.err" || got=$?
  return "$got"
}

fresh
if snap && [ "$(jq -c '[.prs[] | [.pr, .base.kind]]' "$tmp/snap.json")" = '[[7,"clean"],[8,"conflict"],[9,"current"]]' ]; then
  ok "each base is read: a clean replay, a conflict, a head on main"
else
  bad "each base is read: a clean replay, a conflict, a head on main" "$(cat "$tmp/snap.err")" "$(head -c 600 "$tmp/snap.json")"
fi
replay=$(jq -r '.prs[] | select(.pr == 7) | .base.replay' "$tmp/snap.json")
if [ "$(g rev-parse "$replay^{tree}" 2>/dev/null)" = "$rebased" ] && [ "$(g rev-parse "$replay^")" = "$m2" ]; then
  ok "the replay has the tree of git rebase, on main"
else
  bad "the replay has the tree of git rebase, on main" "replay $replay"
fi
if [ "$(jq -r --arg a "$p1" --arg r "$replay" '.prs[] | select(.pr == 7) | [.ids[] | select(.sha == $a or .sha == $r) | .id] | unique | length' "$tmp/snap.json")" = 1 ]; then
  ok "the replay keeps the head's content id"
else
  bad "the replay keeps the head's content id" "$(jq -c '.prs[0].ids' "$tmp/snap.json")"
fi
if [ ! -s "$tmp/snap.err" ] && [ "$(grep -c '' "$tmp/snap.json")" = 1 ]; then
  ok "all read: one line of JSON, nothing on standard error"
else
  bad "all read: one line of JSON, nothing on standard error" "$(cat "$tmp/snap.err")"
fi

expect_land() {
  local name=$1 filter=$2 want=$3
  if ! snap; then bad "$name" "snapshot failed: $(cat "$tmp/snap.err")"; return; fi
  if ! decide "$filter"; then bad "$name" "land refused: $(cat "$tmp/land.err")"; return; fi
  if [ "$(cat "$tmp/land.out")" != "$want" ]; then bad "$name" "got:  $(cat "$tmp/land.out")" "want: $want"; return; fi
  ok "$name"
}
fresh
expect_land "the owner's /land on a head already on main goes first, and nothing is pushed" "$me7" \
  '{"next":9,"plan":{"kind":"idle"},"step":{"ahead":9,"kind":"wait"}}'
fresh
echo '[[]]' >"$d/comments-9.json"
expect_land "with no word on the head on main, the clean replay is pushed" "$me7" \
  "{\"next\":7,\"plan\":{\"expect\":\"$p1\",\"kind\":\"push\",\"pr\":7,\"replay\":\"$replay\"},\"step\":{\"head\":\"$p1\",\"kind\":\"awaitPush\"}}"
fresh
expect_land "a conflict is stuck" '. + {me: {provider: "claude", name: "orchestrator"}, pr: 8}' \
  '{"next":9,"plan":{"kind":"idle"},"step":{"kind":"stop","stuck":"conflict","why":"stuck"}}'

held='{"kind":"stop","why":"held"}'
holds() {
  local name=$1 pat=$2 step
  if ! snap; then bad "$name" "snapshot failed: $(cat "$tmp/snap.err")"; return; fi
  if ! grep -qE -- "$pat" "$tmp/snap.err"; then bad "$name" "stderr: $(cat "$tmp/snap.err")" "want: $pat"; return; fi
  if ! decide "$me7"; then bad "$name" "land refused: $(cat "$tmp/land.err")"; return; fi
  step=$(jq -c .step "$tmp/land.out")
  if [ "$step" != "$held" ]; then bad "$name" "step: $step"; return; fi
  ok "$name"
}
for r in comments review-comments reviews files checks activity; do
  fresh
  rm "$d/$r-7.json"
  holds "a failed read of $r holds the pull request" "^snapshot: #7 holds: unread $r\$"
done
for r in protection stacks dashboard; do
  fresh
  rm "$d/$r.json"
  holds "a failed read of $r holds every pull request" "^snapshot: #9 holds: unread $r\$"
done
fresh
echo '{"message":"Not Found"}' >"$d/comments-7.json"
holds "comments that are not a list of pages hold" "#7 holds: unread comments$"
fresh
echo '[]' >"$d/comments-7.json"
holds "a list of no pages is a failed read" "#7 holds: unread comments$"
fresh
jq -n '[[range(3000) | {filename: "f\(.)"}]]' >"$d/files-7.json"
holds "3000 files may be a cut list, so they hold" "#7 holds: unread files$"
fresh
jq '.[0].total_count = 2' "$b/checks-7.json" >"$d/checks-7.json"
holds "check runs fewer than total_count hold" "#7 holds: unread checks$"
fresh
jq --arg h "$c1" '.[0][0].after = $h' "$b/activity-7.json" >"$d/activity-7.json"
holds "activity that ends at another head holds" "#7 holds: unread activity$"
fresh
jq '.[0][0].before = "HEAD"' "$b/activity-7.json" >"$d/activity-7.json"
holds "activity with a commit that is not a sha holds" "#7 holds: unread activity$"
fresh
jq '.user.login = "someone"' "$b/dashboard.json" >"$d/dashboard.json"
holds "a dashboard from another login holds every pull request" "#7 holds: unread dashboard$"
fresh
jq '.pull_request = {}' "$b/dashboard.json" >"$d/dashboard.json"
holds "a pull request titled Owner dashboard is no dashboard" "#7 holds: unread dashboard$"
fresh
jq --arg body "$(dash_body "$(row 7 "$p1")")" '.body = $body' "$b/dashboard.json" >"$d/dashboard.json"
holds "two rows for one pull request hold every pull request" "#7 holds: unread dashboard$"
fresh
echo '[[]]' >"$d/comments-9.json"
# shellcheck disable=SC2016
jq --arg body "$(dash_body "$(printf '#7 y | `%s` | red | FAIL opus-xhigh at `%s` |' "${p1:0:7}" "${p1:0:7}")")" \
  '.body = $body' "$b/dashboard.json" >"$d/dashboard.json"
holds "a FAIL row without the leading pipe holds every pull request" "#7 holds: unread dashboard$"
if snap && decide "$me7" && [ "$(jq -c .plan "$tmp/land.out")" = '{"kind":"idle"}' ]; then
  ok "a FAIL row without the leading pipe pushes nothing"
else
  bad "a FAIL row without the leading pipe pushes nothing" "$(cat "$tmp/land.out" "$tmp/land.err")"
fi
fresh
jq '.enforce_admins.enabled = false' "$b/protection.json" >"$d/protection.json"
expect_land "protection that lets admins bypass lands nothing" "$me7" \
  '{"next":null,"plan":{"kind":"idle"},"step":{"kind":"stop","why":"unenforced"}}'
fresh
jq '.[0][0] |= (.updated_at = "2026-11-14T08:00:05Z")' "$b/comments-7.json" >"$d/comments-7.json"
expect_land "an edited /land holds" "$me7" \
  '{"next":9,"plan":{"kind":"idle"},"step":{"kind":"stop","why":"held"}}'
fresh
jq '.[0][0].performed_via_github_app = {slug: "claude"}' "$b/comments-7.json" >"$d/comments-7.json"
expect_land "an app's /land is no entry" "$me7" \
  '{"next":9,"plan":{"kind":"idle"},"step":{"kind":"stop","why":"noEntry"}}'
fresh
sed 's/author sonnet/author opus/g' "$b/dashboard.json" >"$d/dashboard.json"
expect_land "a pass on the author's model covers nothing" "$me7" \
  '{"next":null,"plan":{"kind":"idle"},"step":{"kind":"stop","why":"notEligible"}}'

errs() {
  local name=$1 pat=$2 got=0
  (cd "$repo" && "$bin" snapshot "$d") >"$tmp/snap.json" 2>"$tmp/snap.err" || got=$?
  if [ "$got" != 1 ] || [ -s "$tmp/snap.json" ]; then bad "$name" "exit $got, stdout: $(head -c 200 "$tmp/snap.json")"; return; fi
  if [ "$(grep -c '' "$tmp/snap.err")" != 1 ] || ! grep -qE -- "^snapshot: $pat" "$tmp/snap.err"; then
    bad "$name" "stderr: $(cat "$tmp/snap.err")" "want: $pat"
    return
  fi
  ok "$name"
}
fresh
rm "$d/open.json"
errs "no list of open pull requests is an error" "the list of open pull requests is missing"
fresh
jq '.[0][0].head.sha = "zz"' "$b/open.json" >"$d/open.json"
errs "a pull request whose head is not a sha is an error" "the list of open pull requests is not of its route's shape"
fresh
rm "$d/repo.json"
errs "no repository read is an error" "the repository read is missing"
fresh
echo '{"commit":{}}' >"$d/main.json"
errs "no commit of main is an error" "the read of main has no commit"
fresh
jq -n --arg s "$(printf 'f%.0s' {1..40} | tr f e)" '{commit: {sha: $s}}' >"$d/main.json"
errs "a commit of main that the clone lacks and cannot fetch is an error" "main's commit"
got=0
"$bin" snapshot >/dev/null 2>"$tmp/err" || got=$?
if [ "$got" = 2 ]; then ok "no folder is a usage error"; else bad "no folder is a usage error" "exit $got"; fi

fresh
snap
got=0
jq -c '. + {event: {kind: "gateDone", pr: 5, gate: "success"}}' "$tmp/snap.json" | "$bin" land >"$tmp/land.out" 2>"$tmp/land.err" || got=$?
if [ "$got" = 1 ] && grep -qx 'land: the snapshot is refused: event.pr: pull request 5 is not in prs' "$tmp/land.err"; then
  ok "land refuses an event about a pull request the snapshot did not read"
else
  bad "land refuses an event about a pull request the snapshot did not read" "exit $got: $(cat "$tmp/land.err")"
fi
got=0
jq -c '. + {event: {kind: "gateDone", pr: 9, gate: "success"}}' "$tmp/snap.json" | "$bin" land >"$tmp/land.out" 2>"$tmp/land.err" || got=$?
if [ "$got" = 0 ] && [ "$(jq -c .wake "$tmp/land.out")" = '{"kind":"nobody"}' ]; then
  ok "land decides an event about a pull request the snapshot read"
else
  bad "land decides an event about a pull request the snapshot read" "exit $got: $(cat "$tmp/land.out" "$tmp/land.err")"
fi

fake="$tmp/fake"
mkdir -p "$fake"
cat >"$fake/gh" <<'EOF'
#!/usr/bin/env bash
printf '%s\n' "$*" >>"$FAKE_LOG"
case "$*" in
  *"pulls?state=open"*)
    printf '[[{"number":7,"head":{"sha":"%s","ref":"pr"}},{"number":8,"head":{"sha":"%s","ref":"-x"}},{"number":9,"head":{"sha":"zz","ref":"a b"}}]]' "$FAKE_SHA" "$FAKE_SHA" ;;
  *"/issues/7/comments"*) printf '[[{"id":1}]]'; exit 1 ;;
  *"branches/main/protection"*) exit 1 ;;
  *) printf '{}' ;;
esac
EOF
chmod +x "$fake/gh"
fetch() {
  local got=0
  PATH="$fake:$PATH" FAKE_LOG="$tmp/gh.log" FAKE_SHA="$p1" "$root/gate/snapshot-fetch.sh" "$@" \
    >"$tmp/fetch.out" 2>"$tmp/fetch.err" || got=$?
  return "$got"
}
rm -f "$tmp/gh.log"
if fetch owner/mitos 43 "$tmp/f"; then
  have=$(find "$tmp/f" -mindepth 1 -printf '%f\n' | sort | paste -sd' ' -)
  want="activity-7.json checks-7.json checks-8.json comments-8.json comments-9.json dashboard.json files-7.json files-8.json files-9.json main.json open.json repo.json review-comments-7.json review-comments-8.json review-comments-9.json reviews-7.json reviews-8.json reviews-9.json stacks.json"
  want=$(tr ' ' '\n' <<<"$want" | sort | paste -sd' ' -)
  if [ "$have" = "$want" ]; then
    ok "fetch: a failed read leaves no file, even after a first page"
  else
    bad "fetch: a failed read leaves no file, even after a first page" "have: $have" "want: $want"
  fi
  if [ "$(cat "$tmp/fetch.err")" = "$(printf 'snapshot-fetch: the read of protection failed\nsnapshot-fetch: the read of comments-7 failed')" ]; then
    ok "fetch: one line per failed read"
  else
    bad "fetch: one line per failed read" "$(cat "$tmp/fetch.err")"
  fi
  if grep -q 'repos/owner/mitos/activity?ref=refs/heads/pr&direction=desc&per_page=100' "$tmp/gh.log" \
    && ! grep -qi graphql "$tmp/gh.log" && [ "$(grep -c '^api ' "$tmp/gh.log")" = "$(grep -c '' "$tmp/gh.log")" ] \
    && ! grep -q 'refs/heads/-x' "$tmp/gh.log" && ! grep -q 'commits/zz' "$tmp/gh.log"; then
    ok "fetch: REST only, and no route built from a bad ref or sha"
  else
    bad "fetch: REST only, and no route built from a bad ref or sha" "$(cat "$tmp/gh.log")"
  fi
else
  bad "fetch: a failed read leaves no file, even after a first page" "exit non-zero: $(cat "$tmp/fetch.err")"
fi
refuses() {
  local args="$*"
  if fetch "$@"; then
    bad "fetch refuses: $args" "exit 0"
  elif [ "$(grep -c '' "$tmp/fetch.err")" = 1 ] && grep -q '^snapshot-fetch: ' "$tmp/fetch.err"; then
    ok "fetch refuses: ${args//$tmp/<tmp>}"
  else
    bad "fetch refuses: $args" "$(cat "$tmp/fetch.err")"
  fi
}
refuses owner/mitos 43
refuses owner 43 "$tmp/g"
refuses owner/mitos 0 "$tmp/g"
refuses owner/.. 43 "$tmp/g"
refuses owner/mitos 43 "$tmp/f"

echo
echo "$pass passed, $fail failed"
[ "$fail" = 0 ]
