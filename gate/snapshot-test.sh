#!/usr/bin/env bash
set -u

root=$(cd "$(dirname "$0")/.." && pwd)
(cd "$root" && lake build mitos-gate >/dev/null) || { echo "FAIL lake build mitos-gate"; exit 1; }
bin="$root/.lake/build/bin/mitos-gate"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

pass=0
fail=0
ok() { echo "ok   $1"; pass=$((pass + 1)); }
bad() {
  echo "FAIL $1"
  shift
  for l in "$@"; do echo "  | $l"; done
  fail=$((fail + 1))
}

repo="$tmp/repo"
g() { git -C "$repo" -c user.name=test -c user.email=test@example.invalid -c commit.gpgsign=false "$@"; }
mkdir -p "$repo"
g init -q -b main
seq 1 30 >"$repo/a.txt"
g add -A
g commit -qm M1
m1=$(g rev-parse HEAD)
g checkout -qb pr
sed -i '1s/.*/one/' "$repo/a.txt"
g commit -qam P1
p1=$(g rev-parse HEAD)
g checkout -qb conflict "$m1"
sed -i '30s/.*/thirty-c/' "$repo/a.txt"
g commit -qam C1
c1=$(g rev-parse HEAD)
g checkout -q main
sed -i '30s/.*/thirty/' "$repo/a.txt"
g commit -qam M2
m2=$(g rev-parse HEAD)
g checkout -qb current
echo b >"$repo/b.txt"
g add -A
g commit -qm Q1
q1=$(g rev-parse HEAD)
g checkout -q --detach "$p1"
g rebase -q main
rebased=$(g rev-parse 'HEAD^{tree}')
g checkout -q main

zero=0000000000000000000000000000000000000000
body=$(printf 'Why.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_')
b="$tmp/base"
mkdir -p "$b"
echo '{"full_name":"owner/mitos","owner":{"login":"owner"}}' >"$b/repo.json"
pr_json() {
  jq -n --argjson n "$1" --arg sha "$2" --arg ref "$3" --arg body "$body" \
    '{number: $n, user: {login: "owner"}, state: "open", draft: false, labels: [], body: $body,
      head: {sha: $sha, ref: $ref, repo: {full_name: "owner/mitos"}},
      base: {ref: "main", repo: {full_name: "owner/mitos"}}}'
}
jq -n --argjson a "$(pr_json 7 "$p1" pr)" --argjson c "$(pr_json 8 "$c1" conflict)" \
  --argjson q "$(pr_json 9 "$q1" current)" '[[$a, $c, $q]]' >"$b/open.json"
jq -n --arg s "$m2" '{commit: {sha: $s}}' >"$b/main.json"
echo '{"enforce_admins":{"enabled":true},"required_status_checks":{"strict":true,"contexts":["gate"],"checks":[{"context":"gate","app_id":15368}]}}' \
  >"$b/protection.json"
echo '[[]]' >"$b/stacks.json"
# shellcheck disable=SC2016
row() { printf '| #%s x | `%s` | green | PASS opus-xhigh at `%s`, author sonnet |\n' "$1" "${2:0:7}" "${2:0:7}"; }
dash_body() {
  # shellcheck disable=SC2016
  printf '## Needs you\n\n- nothing\n\n## In flight\n\n| PR | Head | `gate` | Verdict |\n|---|---|---|---|\n%s\n\n## Next up\n' \
    "$(row 7 "$p1"; row 8 "$c1"; row 9 "$q1"; printf "%s" "${1:-}")"
}
source_payload() {
  jq -cnS --arg a "$p1" --arg b "$c1" --arg c "$q1" '
    def p($n; $head): {number: $n,
      author: {head: $head, provider: "claude", actor: "builder", actualModel: "claude-sonnet-5-5"},
      verdicts: [{head: $head, provider: "claude", actor: "reviewer", actualModel: "claude-opus-4-6",
        effort: "xhigh", result: "pass", order: 1,
        evidence: "https://github.com/owner/mitos/pull/\($n)#issuecomment-1"}]};
    {version: 1, repository: "owner/mitos", pulls: [p(7; $a), p(8; $b), p(9; $c)]}'
}
source_payload >"$tmp/source.json"
"$bin" provenance render owner/mitos "$tmp/source.json" >"$tmp/source.block" || exit 1
publish() {
  jq -n --arg body "$(dash_body)$(printf '\n\n'; cat "$tmp/source.block")" \
    '{title: "Owner dashboard", user: {login: "owner"}, state: "open", body: $body}'
}
publish >"$b/dashboard.json"
per_pr() {
  local n=$1 h=$2 file=$3
  jq -n --argjson id "${n}001" \
    '[[{id: $id, user: {login: "owner"}, performed_via_github_app: null,
        created_at: "2026-11-14T08:00:00Z", updated_at: "2026-11-14T08:00:00Z", body: "/land"}]]' \
    >"$b/comments-$n.json"
  echo '[[]]' >"$b/review-comments-$n.json"
  jq -n --arg h "$h" '[[{id: 1, user: {login: "coderabbitai[bot]"}, state: "COMMENTED",
      commit_id: $h, submitted_at: "2026-11-14T07:30:00Z", body: "Review."}]]' >"$b/reviews-$n.json"
  jq -n --arg f "$file" '[[{filename: $f}]]' >"$b/files-$n.json"
  jq -n --arg h "$h" '[{total_count: 1, check_runs: [{id: 10, name: "gate",
      app: {slug: "github-actions"}, head_sha: $h, status: "completed", conclusion: "success"}]}]' \
    >"$b/checks-$n.json"
  jq -n --arg h "$h" --arg z "$zero" '[[{timestamp: "2026-11-14T07:00:00Z",
      activity_type: "branch_creation", actor: {login: "owner"}, before: $z, after: $h}]]' \
    >"$b/activity-$n.json"
}
per_pr 7 "$p1" a.txt
per_pr 8 "$c1" a.txt
per_pr 9 "$q1" b.txt

d="$tmp/d"
fresh() { rm -rf "$d"; cp -r "$b" "$d"; }
snap() {
  local got=0
  (cd "$repo" && "$bin" snapshot "$d") >"$tmp/snap.json" 2>"$tmp/snap.err" || got=$?
  return "$got"
}
me7='. + {me: {provider: "claude", name: "orchestrator"}, pr: 7}'
decide() {
  local got=0
  jq -c "$1" "$tmp/snap.json" | "$bin" land >"$tmp/land.out" 2>"$tmp/land.err" || got=$?
  return "$got"
}

fresh
if snap && [ "$(jq -c '[.prs[] | [.pr, .base.kind]]' "$tmp/snap.json")" = '[[7,"clean"],[8,"conflict"],[9,"current"]]' ]; then
  ok "each base is read: a clean replay, a conflict, a head on main"
else
  bad "each base is read: a clean replay, a conflict, a head on main" "$(cat "$tmp/snap.err")" "$(head -c 600 "$tmp/snap.json")"
fi
replay=$(jq -r '.prs[] | select(.pr == 7) | .base.replay' "$tmp/snap.json")
if [ "$(g rev-parse "$replay^{tree}" 2>/dev/null)" = "$rebased" ] && [ "$(g rev-parse "$replay^")" = "$m2" ]; then
  ok "the replay has the tree of git rebase, on main"
else
  bad "the replay has the tree of git rebase, on main" "replay $replay"
fi
if [ "$(jq -r --arg a "$p1" --arg r "$replay" '.prs[] | select(.pr == 7) | [.ids[] | select(.sha == $a or .sha == $r) | .id] | unique | length' "$tmp/snap.json")" = 1 ]; then
  ok "the replay keeps the head's content id"
else
  bad "the replay keeps the head's content id" "$(jq -c '.prs[0].ids' "$tmp/snap.json")"
fi
if [ ! -s "$tmp/snap.err" ] && [ "$(grep -c '' "$tmp/snap.json")" = 1 ]; then
  ok "all read: one line of JSON, nothing on standard error"
else
  bad "all read: one line of JSON, nothing on standard error" "$(cat "$tmp/snap.err")"
fi

expect_land() {
  local name=$1 filter=$2 want=$3
  if ! snap; then bad "$name" "snapshot failed: $(cat "$tmp/snap.err")"; return; fi
  if ! decide "$filter"; then bad "$name" "land refused: $(cat "$tmp/land.err")"; return; fi
  if [ "$(cat "$tmp/land.out")" != "$want" ]; then bad "$name" "got:  $(cat "$tmp/land.out")" "want: $want"; return; fi
  ok "$name"
}
fresh
expect_land "the owner's /land on a head already on main goes first, and its plan is that merge" "$me7" \
  "{\"next\":9,\"plan\":{\"head\":\"$q1\",\"kind\":\"merge\",\"pr\":9},\"step\":{\"ahead\":9,\"kind\":\"wait\"},\"word\":\"stands\"}"
fresh
echo '[[]]' >"$d/comments-9.json"
expect_land "with no word on the head on main, the clean replay is pushed" "$me7" \
  "{\"next\":7,\"plan\":{\"expect\":\"$p1\",\"kind\":\"push\",\"pr\":7,\"replay\":\"$replay\"},\"step\":{\"head\":\"$p1\",\"kind\":\"awaitPush\"},\"word\":\"stands\"}"
fresh
expect_land "a conflict is stuck" '. + {me: {provider: "claude", name: "orchestrator"}, pr: 8}' \
  "{\"next\":9,\"plan\":{\"head\":\"$q1\",\"kind\":\"merge\",\"pr\":9},\"step\":{\"kind\":\"stop\",\"stuck\":\"conflict\",\"why\":\"stuck\"},\"word\":\"stands\"}"

held='{"kind":"stop","why":"held"}'
holds() {
  local name=$1 pat=$2 step
  if ! snap; then bad "$name" "snapshot failed: $(cat "$tmp/snap.err")"; return; fi
  if ! grep -qE -- "$pat" "$tmp/snap.err"; then bad "$name" "stderr: $(cat "$tmp/snap.err")" "want: $pat"; return; fi
  if ! decide "$me7"; then bad "$name" "land refused: $(cat "$tmp/land.err")"; return; fi
  step=$(jq -c .step "$tmp/land.out")
  if [ "$step" != "$held" ]; then bad "$name" "step: $step"; return; fi
  ok "$name"
}
for r in comments review-comments reviews files checks activity; do
  fresh
  rm "$d/$r-7.json"
  holds "a failed read of $r holds the pull request" "^snapshot: #7 holds: unread $r\$"
done
for r in protection stacks dashboard; do
  fresh
  rm "$d/$r.json"
  holds "a failed read of $r holds every pull request" "^snapshot: #9 holds: unread $r(, provenance)?\$"
done
fresh
echo '{"message":"Not Found"}' >"$d/comments-7.json"
holds "comments that are not a list of pages hold" "#7 holds: unread comments$"
fresh
echo '[]' >"$d/comments-7.json"
holds "a list of no pages is a failed read" "#7 holds: unread comments$"
fresh
jq -n '[[range(3000) | {filename: "f\(.)"}]]' >"$d/files-7.json"
holds "3000 files may be a cut list, so they hold" "#7 holds: unread files$"
fresh
jq '.[0].total_count = 2' "$b/checks-7.json" >"$d/checks-7.json"
holds "check runs fewer than total_count hold" "#7 holds: unread checks$"
fresh
jq --arg h "$c1" '.[0][0].after = $h' "$b/activity-7.json" >"$d/activity-7.json"
holds "activity that ends at another head holds" "#7 holds: unread activity$"
fresh
jq '.[0][0].before = "HEAD"' "$b/activity-7.json" >"$d/activity-7.json"
holds "activity with a commit that is not a sha holds" "#7 holds: unread activity$"
fresh
jq '.user.login = "someone"' "$b/dashboard.json" >"$d/dashboard.json"
holds "a dashboard from another login holds every pull request" "#7 holds: unread dashboard(, provenance)?$"
fresh
jq '.pull_request = {}' "$b/dashboard.json" >"$d/dashboard.json"
holds "a pull request titled Owner dashboard is no dashboard" "#7 holds: unread dashboard(, provenance)?$"
fresh
jq --arg body "$(dash_body "$(row 7 "$p1")")" '.body = $body' "$b/dashboard.json" >"$d/dashboard.json"
holds "two rows for one pull request hold every pull request" "#7 holds: unread dashboard(, provenance)?$"
fresh
echo '[[]]' >"$d/comments-9.json"
# shellcheck disable=SC2016
jq --arg body "$(dash_body "$(printf '#7 y | `%s` | red | FAIL opus-xhigh at `%s` |' "${p1:0:7}" "${p1:0:7}")")" \
  '.body = $body' "$b/dashboard.json" >"$d/dashboard.json"
holds "a FAIL row without the leading pipe holds every pull request" "#7 holds: unread dashboard(, provenance)?$"
if snap && decide "$me7" && [ "$(jq -c .plan "$tmp/land.out")" = '{"kind":"idle"}' ]; then
  ok "a FAIL row without the leading pipe pushes nothing"
else
  bad "a FAIL row without the leading pipe pushes nothing" "$(cat "$tmp/land.out" "$tmp/land.err")"
fi
# shellcheck disable=SC2016
fail7=$(printf '| PR | Head | `gate` | Verdict |\n|---|---|---|---|\n| #7 y | `%s` | red | FAIL opus-xhigh at `%s` |' "${p1:0:7}" "${p1:0:7}")
# shellcheck disable=SC2016
for hide in 'an HTML comment:<!--:-->' 'a code fence:```:```'; do
  IFS=: read -r what open close <<<"$hide"
  fresh
  echo '[[]]' >"$d/comments-9.json"
  jq --arg body "$(dash_body "$(printf '\n%s\n## old\n%s\n\n%s' "$open" "$close" "$fail7")")" \
    '.body = $body' "$b/dashboard.json" >"$d/dashboard.json"
  holds "a heading in $what above a FAIL table holds every pull request" "#7 holds: unread dashboard(, provenance)?$"
  if snap && decide "$me7" && [ "$(jq -c .plan "$tmp/land.out")" = '{"kind":"idle"}' ]; then
    ok "a heading in $what above a FAIL table pushes nothing"
  else
    bad "a heading in $what above a FAIL table pushes nothing" "$(cat "$tmp/land.out" "$tmp/land.err")"
  fi
done
fresh
jq '.enforce_admins.enabled = false' "$b/protection.json" >"$d/protection.json"
expect_land "protection that lets admins bypass lands nothing" "$me7" \
  '{"next":null,"plan":{"kind":"idle"},"step":{"kind":"stop","why":"unenforced"},"word":"stands"}'
fresh
jq '.[0][0] |= (.updated_at = "2026-11-14T08:00:05Z")' "$b/comments-7.json" >"$d/comments-7.json"
expect_land "an edited /land holds" "$me7" \
  "{\"next\":9,\"plan\":{\"head\":\"$q1\",\"kind\":\"merge\",\"pr\":9},\"step\":{\"kind\":\"stop\",\"why\":\"held\"},\"word\":\"held\"}"
fresh
jq '.[0][0].performed_via_github_app = {slug: "claude"}' "$b/comments-7.json" >"$d/comments-7.json"
expect_land "an app's /land is no entry" "$me7" \
  "{\"next\":9,\"plan\":{\"head\":\"$q1\",\"kind\":\"merge\",\"pr\":9},\"step\":{\"kind\":\"stop\",\"why\":\"noEntry\"},\"word\":\"none\"}"
fresh
jq -cS '.pulls[].author.actualModel = "claude-opus-4-6"' "$tmp/source.json" >"$tmp/same-model.json"
"$bin" provenance render owner/mitos "$tmp/same-model.json" >"$tmp/same-model.block"
jq --arg body "$(dash_body)$(printf '\n\n'; cat "$tmp/same-model.block")" '.body = $body' \
  "$b/dashboard.json" >"$d/dashboard.json"
expect_land "a pass on the author's model covers nothing" "$me7" \
  '{"next":null,"plan":{"kind":"idle"},"step":{"kind":"stop","why":"notEligible"},"word":"stands"}'

prepare_native_hook() {
  local n
  rm -rf "$tmp/native-hook"
  mkdir -p "$tmp/native-hook"
  jq '.[0]' "$d/open.json" >"$tmp/native-hook/open.json"
  cp "$d/dashboard.json" "$tmp/native-hook/dash.json"
  for n in 7 8 9; do
    if [ -e "$d/files-$n.json" ]; then
      jq '.[0]' "$d/files-$n.json" >"$tmp/native-hook/files-$n.json"
    fi
    cp "$d/activity-$n.json" "$tmp/native-hook/activity-$n.json"
  done
}

refused_dashboard() {
  local name=$1 filter=$2 status=0
  fresh
  jq "$filter" "$b/dashboard.json" >"$d/dashboard.json"
  prepare_native_hook
  (cd "$repo" && "$bin" provenance hook "$tmp/native-hook" owner/mitos owner "$m2") \
    >"$tmp/admission.json" 2>"$tmp/admission.err" || status=$?
  if [ "$status" = 1 ] && [ ! -s "$tmp/admission.json" ]; then ok "$name"
  else bad "$name" "native exit $status: $(cat "$tmp/admission.json")"; fi
}
refused_dashboard "the native hook refuses another dashboard author" '.user.login = "someone"'
refused_dashboard "the native hook refuses another dashboard title" '.title = "Another dashboard"'
refused_dashboard "the native hook refuses a closed dashboard" '.state = "closed"'
refused_dashboard "the native hook refuses a dashboard carrying a pull_request marker" '.pull_request = {}'

native_hook_matches() {
  local wanted=${1:-} hook_wanted=${2:-} expected
  prepare_native_hook
  jq -c '{prs:[.prs[0] | .updatable = true | .enforced = true | .base = {kind:"current"} |
      .gate = "success" | .words = [] | .botAt = .head],
      me:{provider:"claude",name:"orchestrator"},pr:7}' "$tmp/snap.json" |
    "$bin" land >"$tmp/policy-decision.json" || return 1
  expected=$(jq -c '.step.why != "notEligible"' "$tmp/policy-decision.json")
  [ -z "$wanted" ] || [ "$expected" = "$wanted" ] || return 1
  [ -z "$hook_wanted" ] || expected=$hook_wanted
  (cd "$repo" && "$bin" provenance candidates "$tmp/native-hook" owner/mitos owner) \
    >"$tmp/candidates.json" 2>"$tmp/candidates.err" &&
  (cd "$repo" && "$bin" provenance hook "$tmp/native-hook" owner/mitos owner "$m2") \
    >"$tmp/admission.json" 2>"$tmp/admission.err" &&
  jq -e --argjson expected "$expected" --slurpfile c "$tmp/candidates.json" \
    '.["7"].eligible == $expected and .["7"].candidate == $c[0]["7"].candidate and
      all($c[0][]; .eligible == false)' "$tmp/admission.json" >/dev/null
}

source_case() {
  local name=$1 filter=$2 check=$3 mode=${4:-critical} wanted=${5:-}
  fresh
  jq -cS "$filter" "$tmp/source.json" >"$tmp/mutated.json" || { bad "$name" "mutation failed"; return; }
  if ! "$bin" provenance render owner/mitos "$tmp/mutated.json" >"$tmp/mutated.block"; then
    bad "$name" "renderer refused"; return
  fi
  jq --arg body "$(dash_body)$(printf '\n\n'; cat "$tmp/mutated.block")" '.body = $body' \
    "$b/dashboard.json" >"$d/dashboard.json"
  if [ "$mode" = critical ]; then
    echo '[[{"filename":"gate/Main.lean"}]]' >"$d/files-7.json"
  else
    echo '[[{"filename":"ordinary.txt"}]]' >"$d/files-7.json"
    if [ "$mode" = label ]; then
      jq '.[0][0].labels = [{name:"spec-approved"}]' "$b/open.json" >"$d/open.json"
    fi
  fi
  if snap && jq -e "$check" "$tmp/snap.json" >/dev/null &&
      native_hook_matches "$wanted"; then
    ok "$name"
    cp "$tmp/snap.json" "$tmp/v2-snap.json"
    cp "$tmp/candidates.json" "$tmp/v2-candidates.json"
    cp "$tmp/admission.json" "$tmp/v2-admission.json"
    jq --arg dash "$(dash_body)" --rawfile raw "$tmp/mutated.json" \
      '.body = $dash + "\n\n<!-- mitos-provenance:v1 -->\n\u0060\u0060\u0060json\n" +
        ($raw | rtrimstr("\n")) + "\n\u0060\u0060\u0060\n<!-- /mitos-provenance:v1 -->"' \
      "$b/dashboard.json" >"$d/dashboard.json"
    if snap && cmp -s "$tmp/snap.json" "$tmp/v2-snap.json" && native_hook_matches "$wanted" &&
        cmp -s "$tmp/candidates.json" "$tmp/v2-candidates.json" &&
        cmp -s "$tmp/admission.json" "$tmp/v2-admission.json"; then
      ok "$name: legacy and v2 preserve exact snapshot facts and native admission"
    else bad "$name: legacy and v2 preserve exact snapshot facts and native admission"; fi
  else bad "$name" "$(cat "$tmp/snap.err")" "$(jq -c '.prs[0]' "$tmp/snap.json")"; fi
}

