#!/usr/bin/env bash
set -u

root=$(cd "$(dirname "$0")/.." && pwd)
(cd "$root" && lake build mitos-gate >/dev/null) || { echo "FAIL lake build mitos-gate"; exit 1; }
bin="$root/.lake/build/bin/mitos-gate"
posts="$root/gate/watch-fixtures/posts-336"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

pass=0
fail=0
ok() { echo "ok   $1"; pass=$((pass + 1)); }
bad() {
  echo "FAIL $1"
  shift
  for l in "$@"; do echo "  | $l"; done
  fail=$((fail + 1))
}

cases=(live class-1 class-2 class-3 class-4-quoted class-4-other-tool)
routes=(issue-comments review-comments reviews)

name="classes.tsv has a row for each of the four classes, each in a case of the suite"
if [ "$(cut -f3 "$posts/classes.tsv" | sort -u | tr '\n' ' ')" = "1 2 3 4 " ] &&
  [ -z "$(cut -f1 "$posts/classes.tsv" | sort -u | comm -23 - <(printf '%s\n' "${cases[@]}" | sort))" ]; then
  ok "$name"
else
  bad "$name" "$(cat "$posts/classes.tsv")"
fi

for case in "${cases[@]}"; do
  files=()
  for route in "${routes[@]}"; do
    if [ "$case" = live ]; then files+=("$posts/$route.json"); continue; fi
    jq -c --arg c "$case" --arg r "$route" --slurpfile add "$posts/added.json" \
      '. + [($add[0][$c][$r] // [])]' "$posts/$route.json" >"$tmp/$case-$route.json"
    files+=("$tmp/$case-$route.json")
  done
  name="posts-336 $case: the answer is the one in expected.json"
  got=0
  "$bin" watch unanswered --owner kitimark --issue-comments "${files[0]}" \
    --review-comments "${files[1]}" --reviews "${files[2]}" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" = 0 ] && [ ! -s "$tmp/err" ] &&
    jq -c --arg c "$case" '.[$c]' "$posts/expected.json" | cmp -s - "$tmp/out"; then
    ok "$name"
  else
    bad "$name" "exit $got, stdout: $(cat "$tmp/out")" "stderr: $(head -n 3 "$tmp/err")"
  fi

  name="posts-336 $case: it differs from the jq of 7dfd6cb on the rows of classes.tsv only"
  if ! jq -n -c --arg owner kitimark --slurpfile ic "${files[0]}" --slurpfile rc "${files[1]}" \
    --slurpfile rv "${files[2]}" -f "$posts/jq-7dfd6cb.jq" >"$tmp/jq.json" 2>"$tmp/err"; then
    bad "$name" "the jq failed: $(head -n 3 "$tmp/err")"
    continue
  fi
  jq -r '.[]' "$tmp/jq.json" | sort >"$tmp/jq"
  jq -r '.["336"] // [] | .[]' "$tmp/out" 2>/dev/null | sort >"$tmp/lean"
  {
    comm -23 "$tmp/jq" "$tmp/lean" | awk '{ print $0 "\tlisted\tnot-listed" }'
    comm -13 "$tmp/jq" "$tmp/lean" | awk '{ print $0 "\tnot-listed\tlisted" }'
  } | sort >"$tmp/differs"
  awk -F'\t' -v c="$case" '$1 == c { print $2 "\t" $4 "\t" $5 }' "$posts/classes.tsv" |
    sort >"$tmp/listed"
  if cmp -s "$tmp/differs" "$tmp/listed"; then
    ok "$name"
  else
    bad "$name" "id, jq, lean:" "$(cat "$tmp/differs")" "classes.tsv:" "$(cat "$tmp/listed")"
  fi
done

at() {
  case $1 in
    *[!0-9]*) printf '%s' "$1" ;;
    *) printf '2026-11-13T12:00:%02dZ' "$1" ;;
  esac
}
issue() {
  printf '{"id":%s,"user":{"login":"%s"},"performed_via_github_app":%s,"created_at":"%s","updated_at":"%s","issue_url":"https://api.github.com/repos/o/r/issues/%s","body":%s}' \
    "$1" "$2" "$3" "$(at "$4")" "$(at "$4")" "$5" "$6"
}
inline() {
  printf '{"id":%s,"user":{"login":"%s"},"created_at":"%s","updated_at":"%s","pull_request_url":"https://api.github.com/repos/o/r/pulls/7","body":%s}' \
    "$1" "$2" "$(at "$3")" "$(at "$3")" "$4"
}
review() {
  printf '{"id":%s,"user":{"login":"o"},"state":"%s","submitted_at":"%s","pull_request_url":"https://api.github.com/repos/o/r/pulls/7","body":%s}' \
    "$1" "$2" "$(at "$3")" "$4"
}
page() {
  local file=$1
  shift
  (IFS=,; echo "[[$*]]") >"$tmp/$file.json"
}

answers() {
  local name=$1 want=$2 got=0
  shift 2
  "$bin" watch unanswered --owner o "$@" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" != 0 ] || [ -s "$tmp/err" ] || ! printf '%s\n' "$want" | cmp -s - "$tmp/out"; then
    bad "$name" "exit $got, stdout: $(cat "$tmp/out")" "want: $want" "stderr: $(head -n 3 "$tmp/err")"
    return
  fi
  ok "$name"
}

refuses() {
  local name=$1 want=$2 pat=$3 got=0
  shift 3
  "$bin" watch "$@" >"$tmp/out" 2>"$tmp/err" || got=$?
  if [ "$got" != "$want" ] || [ -s "$tmp/out" ]; then
    bad "$name" "exit $got (expected $want), stdout: $(cat "$tmp/out")"
    return
  fi
  if ! head -n 1 "$tmp/err" | grep -qE -- "$pat"; then
    bad "$name" "stderr: $(cat "$tmp/err")" "want:   $pat"
    return
  fi
  if [ "$want" = 1 ] && [ "$(grep -c '' "$tmp/err")" != 1 ]; then
    bad "$name" "stderr is not one line: $(cat "$tmp/err")"
    return
  fi
  ok "$name"
}

footer='\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
keyless() {
  issue "$1" "$2" null 2 7 '"words"' | jq -c 'del(.performed_via_github_app)'
}

page nokey "$(issue 20 o null 1 7 '"first"')" "$(keyless 21 o)"
refuses "the owner's issue comment without the app key is refused" 1 \
  '^watch unanswered: --issue-comments: issue comment 21 is refused: \[0\]\[1\]\.performed_via_github_app: missing$' \
  unanswered --owner o --issue-comments "$tmp/nokey.json"
page otherskey "$(issue 20 o null 1 7 '"first"')" "$(keyless 21 someone)"
answers "another login's issue comment without the app key is dropped" '{"7":[20]}' \
  --issue-comments "$tmp/otherskey.json"
page nulluser "$(issue 20 o null 1 7 '"first"')" '{"id":22,"user":null}'
answers "an item with a null user is dropped" '{"7":[20]}' --issue-comments "$tmp/nulluser.json"
page nouser '{"id":23,"body":"words"}'
refuses "an item with no user refuses the answer" 1 \
  '^watch unanswered: --issue-comments is refused: \[0\]\[0\]\.user: missing$' \
  unanswered --owner o --issue-comments "$tmp/nouser.json"
page noid "$(issue 24 o null 1 7 '"words"' | jq -c 'del(.id)')"
refuses "the owner's item with no id refuses the answer" 1 \
  '^watch unanswered: --issue-comments is refused: \[0\]\[0\]\.id: missing$' \
  unanswered --owner o --issue-comments "$tmp/noid.json"
page millis "$(inline 25 o 2026-11-13T12:00:01.000Z '"words"')"
refuses "a time of another shape is refused" 1 \
  '^watch unanswered: --review-comments: review comment 25 is refused: \[0\]\[0\]\.created_at: expected YYYY-MM-DDTHH:MM:SSZ$' \
  unanswered --owner o --review-comments "$tmp/millis.json"
echo "[$(issue 26 o null 1 7 '"words"')]" >"$tmp/flat.json"
refuses "an answer read without --slurp is refused" 1 \
  '^watch unanswered: --issue-comments is refused: \[0\]: expected a page, a list of items$' \
  unanswered --owner o --issue-comments "$tmp/flat.json"
echo '{"id":1}' >"$tmp/object.json"
refuses "an object is not a list of pages" 1 \
  '^watch unanswered: --reviews is refused: expected a list of pages$' \
  unanswered --owner o --reviews "$tmp/object.json"
printf '[["\377"]]' >"$tmp/latin.json"
refuses "a file that is not UTF-8 is refused" 1 \
  '^watch unanswered: --reviews is refused: .*latin\.json: not valid UTF-8$' \
  unanswered --owner o --reviews "$tmp/latin.json"
echo '[[{' >"$tmp/cut.json"
refuses "cut JSON is refused" 1 '^watch unanswered: --issue-comments is refused: .*cut\.json: ' \
  unanswered --owner o --issue-comments "$tmp/cut.json"
refuses "a missing file is an I/O error" 1 '^watch unanswered: stopped on an I/O error: ' \
  unanswered --owner o --issue-comments "$tmp/none.json"

page appkey "$(inline 31 o 1 '"words"' | jq -c '.performed_via_github_app = {slug: "claude"}')"
answers "a review comment's app key is not read, so it is words" '{"7":[31]}' \
  --review-comments "$tmp/appkey.json"
page pending '{"id":41,"user":{"login":"o"},"state":"PENDING","pull_request_url":"https://api.github.com/repos/o/r/pulls/7","body":"draft"}'
answers "a pending review is skipped" '{}' --reviews "$tmp/pending.json"
page commented "$(review 42 COMMENTED 1 null)"
answers "a COMMENTED review with no body does not count" '{}' --reviews "$tmp/commented.json"
page approved "$(review 43 APPROVED 1 '""')"
answers "an APPROVED review with an empty body counts" '{"7":[43]}' --reviews "$tmp/approved.json"

page words "$(issue 51 o null 1 7 '"first"')" "$(issue 53 o null 9 7 '"again"')"
page answer "$(review 52 COMMENTED 5 "\"Done.$footer\"")"
answers "a review with a footer answers the words before its submitted_at" '{"7":[53]}' \
  --issue-comments "$tmp/words.json" --reviews "$tmp/answer.json"
answers "a route whose flag is left out has no posts" '{"7":[51,53]}' \
  --issue-comments "$tmp/words.json"
page order "$(issue 5 o null 1 1000 '"a"')" "$(issue 3 o null 2 1000 '"b"')" \
  "$(issue 9 o null 3 999 '"c"')"
answers "one line, with threads and ids in ascending order" '{"999":[9],"1000":[3,5]}' \
  --issue-comments "$tmp/order.json"

refuses "no --owner is a usage error" 2 '^watch unanswered needs --owner <login>$' \
  unanswered --issue-comments "$tmp/order.json"
refuses "an empty --owner is a usage error" 2 '^watch unanswered: --owner is empty$' \
  unanswered --owner '' --issue-comments "$tmp/order.json"
refuses "a flag given twice is a usage error" 2 \
  '^watch unanswered: a flag is unknown, repeated or has no value$' \
  unanswered --owner o --reviews "$tmp/answer.json" --reviews "$tmp/answer.json"
refuses "an unknown flag is a usage error" 2 \
  '^watch unanswered: a flag is unknown, repeated or has no value$' unanswered --owner o --pr 7
refuses "a flag with no value is a usage error" 2 \
  '^watch unanswered: a flag is unknown, repeated or has no value$' unanswered --owner o --reviews
refuses "watch wait is not built yet" 2 '^watch wait is not built yet$' wait --state "$tmp"

audit() {
  printf 'import MitosGate.Watch\n\n%s\n\n#eval show Lean.CoreM Unit from do\n  for n in ← MitosGate.WatchAudit.auditedStatements do IO.println n\n' \
    "$1" >"$tmp/Audit.lean"
  (cd "$root" && lake env lean "$tmp/Audit.lean") >"$tmp/audit" 2>"$tmp/err"
}

planted() {
  local name=$1 pat=$2 got=0
  audit "$3" || got=$?
  if [ "$got" = 0 ] || [ "$(grep -c ': error: ' "$tmp/audit")" != 1 ] ||
    ! grep -qE -- ": error: $pat" "$tmp/audit"; then
    bad "$name" "exit $got" "$(head -n 20 "$tmp/audit" "$tmp/err")"
    return
  fi
  ok "$name"
}

name="Watch.olean is in the build of mitos-gate"
if [ -f "$root/.lake/build/lib/lean/MitosGate/Watch.olean" ]; then ok "$name"; else bad "$name"; fi

statements=(AnAppPostIsNeverWords AnswersAsLandUnlessTyped ExcerptIsOneLine
  ReviewRoutesAreNeverTyped SpeaksAsLandUnlessTyped TypedIsAlwaysWords
  TypedOnlyFromAnIssueCommentWithNoApp TypedWordsAreListedUntilAnswered)
name="the audit finds a theorem for each of the ${#statements[@]} statements, and no other statement"
got=0
audit '' || got=$?
if [ "$got" = 0 ] && printf 'MitosGate.Watch.%s\n' "${statements[@]}" | cmp -s - "$tmp/audit"; then
  ok "$name"
else
  bad "$name" "exit $got" "$(head -n 20 "$tmp/audit" "$tmp/err")"
fi

planted "the audit refuses a statement with no theorem" \
  'the statement MitosGate\.Watch\.Planted has no theorem$' \
  'def MitosGate.Watch.Planted : Prop := True'
planted "the audit refuses a statement written in a variable section" \
  'MitosGate\.Watch\.Planted is a definition into Prop that takes arguments: ' \
  'namespace MitosGate.Watch
section
variable (n : Nat)
def Planted : Prop := n = n
theorem planted : Planted n := rfl
end
end MitosGate.Watch'
planted "the audit refuses a private theorem with sorry" \
  '_private\..*\.MitosGate\.Watch\.planted depends on the axiom sorryAx$' \
  'namespace MitosGate.Watch
private theorem planted : True := sorry
end MitosGate.Watch'
planted "the audit refuses an axiom" \
  'MitosGate\.Watch\.planted depends on the axiom MitosGate\.Watch\.planted$' \
  'axiom MitosGate.Watch.planted : False'

echo "$pass passed, $fail failed"
[ "$fail" = 0 ]
